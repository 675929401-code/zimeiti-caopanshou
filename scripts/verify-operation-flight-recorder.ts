import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (file: string) => readFileSync(file, "utf8");

const migration = read("supabase/migrations/20261001020000_operation_flight_recorder.sql");
const rollback = read("supabase/rollbacks/20261001020000_operation_flight_recorder.rollback.sql");
const sequenceMigration = read("supabase/migrations/20261001030000_operation_flight_recorder_sequence.sql");
const sequenceRollback = read("supabase/rollbacks/20261001030000_operation_flight_recorder_sequence.rollback.sql");
const baseline = read("deploy/local/task-baseline.sql");
const contract = JSON.parse(read("deploy/policies/database-contract.v1.json"));
const recorder = read("src/lib/operation-flight-recorder.ts");
const sentry = read("src/lib/diagnostic-sentry.ts");
const ingest = read("src/app/api/operation-events/route.ts");
const adminList = read("src/app/api/admin/operation-events/route.ts");
const adminTrace = read("src/app/api/admin/operation-events/[traceId]/route.ts");
const component = read("src/components/admin/operation-flight-recorder-panel.tsx");
const adminPage = read("src/app/admin/page.tsx");
const health = read("src/app/api/health/route.ts");

assert.match(migration, /CREATE TABLE IF NOT EXISTS public\.operation_flight_events/u);
assert.match(migration, /CREATE OR REPLACE FUNCTION public\.capture_operation_flight_event/u);
for (const table of ["llm_request_attempts", "image_generation_requests", "video_tasks", "voice_generation_requests", "extraction_attempts"]) {
  assert.match(migration, new RegExp(`'${table}'`, "u"), `TRIGGER_TABLE_MISSING:${table}`);
}
assert.doesNotMatch(migration, /"?prompt"?\s+(?:text|jsonb)|response_body\s+(?:text|jsonb)|signed_url/iu);
assert.match(migration, /Telemetry can never make a paid or user-facing business transaction fail/u);
assert.match(rollback, /DROP TABLE IF EXISTS public\.operation_flight_events/u);
assert.match(baseline, /CREATE TABLE public\."operation_flight_events"/u);
assert.match(sequenceMigration, /capture_sequence bigint GENERATED BY DEFAULT AS IDENTITY/u);
assert.match(sequenceRollback, /DROP COLUMN IF EXISTS capture_sequence/u);
assert.match(adminList, /\.order\("capture_sequence", \{ ascending: false \}\)/u);
assert.match(adminTrace, /\.order\("capture_sequence", \{ ascending: true \}\)/u);

const flightRecorderSequenceVersion = "20261001030000";
assert.match(contract.contractVersion, /^\d{14}$/u, "DATABASE_CONTRACT_VERSION_INVALID");
assert.ok(
  BigInt(contract.contractVersion) >= BigInt(flightRecorderSequenceVersion),
  `DATABASE_CONTRACT_PREDATES_FLIGHT_SEQUENCE:${contract.contractVersion}`,
);
const flightTable = contract.tables.find((table: { name: string }) => table.name === "operation_flight_events");
assert.ok(flightTable, "DATABASE_CONTRACT_FLIGHT_TABLE_MISSING");
for (const column of ["capture_sequence", "trace_id", "source", "domain", "operation", "phase", "outcome", "duration_ms", "source_version", "build_id"]) {
  assert.ok(flightTable.columns.includes(column), `DATABASE_CONTRACT_COLUMN_MISSING:${column}`);
}

assert.match(recorder, /browserOperationFlightEventSchema/u);
assert.match(recorder, /redactOperationText/u);
assert.match(recorder, /OPERATION_ROUTE_INVALID/u);
assert.match(recorder, /source_version:\s*runtime\.sourceVersion/u);
assert.doesNotMatch(recorder, /request_body|response_body|prompt_text/iu);

assert.match(sentry, /x-client-trace-id/u);
assert.match(sentry, /client_request_id/u);
assert.match(sentry, /operationDescriptor/u);
assert.match(sentry, /new URL\(url, window\.location\.origin\)\.origin !== window\.location\.origin/u);
assert.match(sentry, /method !== "GET" && method !== "HEAD"/u);
assert.doesNotMatch(sentry, /let isIntercepting/u, "GLOBAL_FETCH_LOCK_MUST_NOT_RETURN");
assert.match(sentry, /FETCH_NETWORK_ERROR/u);
assert.match(sentry, /isObsoleteNavigationRequest/u);
assert.match(sentry, /isPageRequestObsolete/u);
assert.match(sentry, /if \(isPageRequestObsolete\(signal, startedPageUrl\)\) return response/u);
assert.match(sentry, /signal\?\.aborted === true/u);
assert.match(sentry, /pageLifecycleEnding/u);
assert.match(sentry, /beforeunload/u);
assert.match(sentry, /pagehide/u);
assert.match(sentry, /window\.location\.href !== startedPageUrl/u);

assert.match(ingest, /verifyToken/u);
assert.match(ingest, /MAX_REQUEST_BYTES/u);
assert.match(ingest, /MAX_EVENTS_PER_WINDOW/u);
assert.match(adminList, /authorizeAdminToken/u);
assert.match(adminList, /p95DurationMs/u);
