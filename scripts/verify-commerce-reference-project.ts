import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {parseCopyCues, validateSemanticBeats} from '../src/commerce/shared/reference-copy';
import {parseReferenceBreakdown} from '../src/commerce/server/reference-video-schema';
import {openReferenceProject, referenceProjects} from '../src/commerce-v2/server/reference-projects';
import {readAssist, editAssist} from '../src/commerce/server/prompt-assist';
import {put} from '../src/commerce/server/store';

process.env.COMMERCE_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'commerce-reference-project-'));
const owner='sample-owner', other='other-owner';
const first=openReferenceProject(owner);
assert.equal(openReferenceProject(owner).id,first.id);
const request=crypto.randomUUID();
const next=openReferenceProject(owner,undefined,request);
assert.equal(openReferenceProject(owner,undefined,request).id,next.id);
assert.equal(referenceProjects(owner).length,2);
assert.equal(referenceProjects(other).length,0);
assert.throws(()=>openReferenceProject(other,first.id));
assert.throws(()=>readAssist(other,first.id));
assert.equal(openReferenceProject(owner,first.id).id,first.id);
assert.throws(()=>editAssist(owner,first.id,first.revision,{productAssetIds:['missing']}));
assert.throws(()=>editAssist(owner,first.id,first.revision,{confirmedCopy:'1-2 | 字幕 | 一句'}));
const duration=8;
const evidence={id:'frames',version:'test',assetId:'source',sha256:'hash',durationSeconds:duration,fps:2,hasAudioTrack:true,blackTail:false,frames:[{id:'f1',timeSeconds:0},{id:'f2',timeSeconds:4}]};
const copy='0-3 | 口播 | 抽屉打不开？\n4-8 | 字幕 | 看右边的卡扣';
const cues=parseCopyCues(copy,duration);
assert.equal(cues[1].source,'subtitle');
assert.throws(()=>parseCopyCues('0-9 | 口播 | 越界',duration));
assert.throws(()=>parseCopyCues('一句没有来源的台词',duration));
const shots=[{start:0,end:4,frameIds:['f1']},{start:4,end:8,frameIds:['f2']}].map(s=>({...s,visualText:'',action:'展示抽屉',camera:'固定',transition:''}));
const base={sourceDurationSeconds:8,shootingMethod:null,contentType:null,script:'先提问，然后展示卡扣',shots,audio:{track:'present',speech:'unknown',music:'unknown'},uncertainties:[]};
const beat={shotIndex:0,role:'hook',explanation:'用提问引出卡住的抽屉',cueIds:['c1'],frameIds:['f1']};
assert.deepEqual(parseReferenceBreakdown(JSON.stringify({...base,semantics:[beat]}),evidence,cues).semantics,[beat]);
assert.equal(parseReferenceBreakdown(JSON.stringify(base),evidence).semantics,undefined);
assert.throws(()=>parseReferenceBreakdown(JSON.stringify(base),evidence,cues));
assert.throws(()=>validateSemanticBeats([{...beat,cueIds:['c2']}],shots,cues));
assert.throws(()=>validateSemanticBeats([{...beat,frameIds:['f2']}],shots,cues));
assert.throws(()=>validateSemanticBeats([{...beat,frameIds:[],cueIds:[]}],shots,cues));
assert.throws(()=>validateSemanticBeats([{...beat,role:'missing'}],shots,cues));
const referenceVideo={assetId:'source',sha256:'hash',fileName:'test.mp4',profile:'component60' as const};
put('prompt-assists',first.id,owner,{...first,referenceVideo,preparation:{id:'p',referenceRevision:0,status:'succeeded',evidence},script:'旧脚本',breakdownJobId:'old-job'});
const edited=editAssist(owner,first.id,first.revision,{confirmedCopy:copy});
assert.equal(edited.confirmedCopy,copy);
assert.equal(edited.breakdownJobId,undefined);
assert.equal(edited.script,undefined);
assert.equal(edited.preparation?.evidence?.id,'frames');
assert.throws(()=>editAssist(owner,first.id,first.revision,{confirmedCopy:''}));
assert.equal(readAssist(owner,first.id).confirmedCopy,copy);
const angle=editAssist(owner,first.id,edited.revision,{rewriteAngle:'demonstration'});
assert.equal(angle.rewriteAngle,'demonstration');
assert.equal(readAssist(owner,next.id).confirmedCopy,undefined);
assert.equal(referenceProjects(owner).find(p=>p.id===first.id)?.title,'test.mp4');
console.log('Reference-first workflow passed: owner isolation, idempotent projects, source timing, semantic evidence, stale revisions, legacy results and script invalidation.');
