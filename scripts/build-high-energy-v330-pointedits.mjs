function sha(s) { return crypto.createHash("sha256").update(s).digest("hex"); }

async function main() {
  const base = (await fs.readFile(SRC, "utf8")).replace(/^\uFEFF/u, "");
  let out = base;
  const report = [];

  for (const [label, from, to] of edits) {
    const count = out.split(from).length - 1;
    if (count !== 1) throw new Error(`${label}: expected exactly 1 match, got ${count}`);
    out = out.replace(from, to);
    report.push({ label, ok: true, delta: to.length - from.length });
  }

  out = out.trimEnd() + "\n" + append;

  const baseLines = base.split("\n");
  const outLines = out.split("\n");
  let changed = 0;
  const max = Math.max(baseLines.length, outLines.length);
  for (let i = 0; i < max; i += 1) if (baseLines[i] !== outLines[i]) changed += 1;

  await fs.writeFile(OUT, out, "utf8");
  console.log(JSON.stringify({
    src: { chars: base.length, sha: sha(base) },
    out: { path: OUT, chars: out.length, sha: sha(out) },
    edits: report.length,
    appendedSections: ["N15", "N16", "N17"],
    changedLineCount: changed,
    grewBy: out.length - base.length,
  }, null, 2));
  for (const r of report) console.log(`${r.ok ? "OK " : "FAIL"} ${r.label} (${r.delta > 0 ? "+" : ""}${r.delta})`);
}

main().catch((e) => { console.error("BUILD_FAILED:", e.message); process.exit(1); });
