import assert from "node:assert/strict";
import { authorizationCategory, displayCategory, MEME_STORYBOARD_DIRECTOR_ID, matchesDisplayCategory, taskCategory } from "../src/lib/business-ip/catalog";
import { getAgentNavigationKey, getAuthorizedAgentDisplayKeys, isAgentAuthorizedInSnapshot, resolveAllowedAgentNavigationKeys } from "../src/lib/agent-category-access";

const target = { id: MEME_STORYBOARD_DIRECTOR_ID, name: "爆梗分镜导演", category: "引流带货" };
const ids = new Set([target.id]);
const growth = new Set(["task:获客转化"]);
const film = new Set(["task:影像编导"]);
assert.equal(taskCategory(target), "影像编导");
assert.equal(displayCategory(target), "task:影像编导");
assert.equal(authorizationCategory(target), "task:获客转化");
assert.equal(getAgentNavigationKey(target), "task:获客转化");
assert.equal(matchesDisplayCategory(target, "task:影像编导"), true);
assert.equal(matchesDisplayCategory(target, "task:文案创作"), false);
assert.equal(isAgentAuthorizedInSnapshot(target, ids, growth), true);
assert.equal(isAgentAuthorizedInSnapshot(target, ids, film), false);
assert.equal(isAgentAuthorizedInSnapshot(target, new Set(), growth), false);
assert.equal(isAgentAuthorizedInSnapshot(target, ids, new Set()), false);
assert.deepEqual([...getAuthorizedAgentDisplayKeys([target], ids, growth)], ["task:影像编导"]);
assert.deepEqual([...getAuthorizedAgentDisplayKeys([target], ids, film)], []);
assert.deepEqual([...getAuthorizedAgentDisplayKeys([target], new Set(), growth)], []);
assert.deepEqual(resolveAllowedAgentNavigationKeys(["legacy"], [{ id: "legacy", name: "引流带货" }], [target]), ["task:获客转化"]);
const privateTarget = { ...target, category: "自用" };
assert.equal(displayCategory(privateTarget), "自用");
assert.equal(getAgentNavigationKey(privateTarget), "自用");
const similar = { ...target, id: "other", name: "爆梗分镜导演" };
assert.equal(displayCategory(similar), "task:获客转化");
assert.equal(getAgentNavigationKey(similar), "task:获客转化");
console.log("agent display and authorization separation: passed");
