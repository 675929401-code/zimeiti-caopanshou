import assert from "node:assert/strict";
import { chromium } from "playwright";
import { installStoryboardBrowserFixture } from "./storyboard-browser-fixture.mjs";

const baseUrl = process.env.BASE_URL || "http://127.0.0.1:5000";
const ASSET_URL = "https://example.com/visual-asset-character.svg";
const SVG = '<svg xmlns="http://www.w3.org/2000/svg" width="160" height="90"><rect width="160" height="90" fill="#d8efe9"/><circle cx="80" cy="45" r="24" fill="#126e63"/></svg>';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
const page = await context.newPage();
const fixture = await installStoryboardBrowserFixture(page, { origin: baseUrl });
const requests = [];
await page.route("**/api/cover-models**", (route) => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ models: [{ id: "pm_HabdJ5rvD_L3-HUkfMUmGsrm", name: "GPT-2.5 测试模型", model_name: "gpt-image-2", supports_image_input: true, resolution_options: ["1K"], default_resolution: "1K", selling_price: 0.2, available: true, priceReady: true }] }) }));
await page.route("**/api/video/models**", (route) => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ models: [{ id: "omni-e2e", name: "Omni Flash 10秒测试", price_per_use: 0.55, available: true, priceReady: true, durationSeconds: 10, maxDuration: 10, durationMode: "fixed", supportsImageInput: true, requiresImage: true, resolutionTier: "1080p", resolutionOptions: ["1080p"], defaultResolution: "1080p", aspectRatios: ["16:9", "9:16"], workspaceSurfaces: ["storyboard"] }] }) }));
await page.route("**/api/storyboard/visual-assets**", (route) => {
  if (route.request().method() === "POST") return route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ asset: { assetId: "asset-character-1", storageKey: "images/asset-character-1.png", previewUrl: ASSET_URL, role: "character", name: "主角小雨", projectId: "storyboard-fixture" } }) });
  return route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ assets: [] }) });
});
await page.route("**/api/image/generate", (route) => { requests.push(route.request().postDataJSON()); return route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ images: [{ url: ASSET_URL, assetId: "asset-character-1", storageKey: "images/asset-character-1.png", width: 160, height: 90, deliveryMode: "provider_url" }], cashCharged: 0.2, recordId: "record-character-1" }) }); });
await page.route("**/api/storyboard/image?**", (route) => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ url: ASSET_URL, assetId: "asset-character-1", storageKey: "images/asset-character-1.png" }) }));
await page.route(ASSET_URL, (route) => route.fulfill({ status: 200, contentType: "image/svg+xml", body: SVG }));
await page.goto(`${baseUrl}/storyboard-workbench`, { waitUntil: "domcontentloaded" });
await page.locator(".sbw-shot-card").first().waitFor({ timeout: 30_000 });
assert.equal(await page.locator(".sbw-shot-card").count(), 3);
await page.getByRole("button", { name: "视觉资产工作流", exact: true }).click();
await page.getByRole("button", { name: "生成人物资产预览", exact: true }).waitFor();
await page.getByRole("button", { name: "视觉资产模式", exact: true }).click();
await page.getByRole("textbox", { name: "资产名称（可选）" }).fill("主角小雨");
await page.getByRole("textbox", { name: "资产参考板提示词" }).fill("固定人物资产：年轻亚洲女性，黑色短发，米白夹克，正面、侧面、背面三视图参考板，纯净背景，不带剧情道具。");
await page.getByText("当前项目 3 张任务卡会自动绑定已确认资产", { exact: true }).waitFor();
await page.getByRole("button", { name: "生成人物资产预览", exact: true }).click();
await page.getByText("人物资产预览已生成", { exact: false }).waitFor({ timeout: 30_000 });
assert.equal(requests.length, 1);
assert.equal(requests[0].historySurface, "storyboard-workbench");
assert.equal(requests[0].referenceImageUrls.length, 0);
assert.match(requests[0].prompt, /三视图/u);
const previewOnly = fixture.latestDocument();
assert.ok(previewOnly.cards.every((card) => !card.visualAssetRefs?.length), "生成预览不应自动绑定或保存资产");
await page.getByRole("button", { name: "保存到我的视觉资产并绑定", exact: true }).click();
await page.getByText("资产已保存到“我的视觉资产”", { exact: false }).waitFor({ timeout: 30_000 });
const saved = fixture.latestDocument();
assert.equal(saved.cards.length, 3);
assert.ok(saved.cards.every((card) => card.visualAssetRefs?.length === 1), "资产没有绑定到全部任务卡");
assert.ok(saved.cards.every((card) => card.referenceImageUrls?.length === 1), "资产参考图没有写入全部任务卡");
assert.equal(saved.visualAssetPlan?.mode, "selected");
assert.equal(saved.visualAssetPlan?.assets?.length, 1);
await context.close();
await browser.close();
console.log(JSON.stringify({ passed: true, requests: requests.length, boundCards: saved.cards.length, mode: saved.visualAssetPlan.mode }));
