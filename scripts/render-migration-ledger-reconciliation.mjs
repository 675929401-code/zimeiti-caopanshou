#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const policyPath = path.join(root, "deploy", "policies", "release-policy.json");
const policy = JSON.parse(fs.readFileSync(policyPath, "utf8"));
const migrationRoot = path.join(root, policy.database?.migrationRoot || "supabase/migrations");
const contractPath = path.join(root, policy.database?.semanticContract || "deploy/policies/database-semantic-contract.v1.json");
const outputPath = path.join(
  root,
  policy.database?.migrationLedgerReconciliation?.artifact
    || "deploy/database-repairs/20261009-production-semantic/20261009035000_migration_ledger_reconciliation.sql",
);
const write = process.argv.includes("--write");
const CANONICAL_MIGRATION_FILE = /^(\d{14})_([a-z0-9][a-z0-9_-]*)\.sql$/iu;

function stableJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map((item) => stableJson(item)).join(",")}]`;
  return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${stableJson(value[key])}`).join(",")}}`;
}

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function transactionMode(sql) {
  const statements = sql
    .replace(/^\uFEFF/u, "")
    .split(/\r?\n/u)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("--"));
  const startsWithBegin = /^begin\s*;/iu.test(statements[0] || "");
  const endsWithCommit = /^commit\s*;/iu.test(statements.at(-1) || "");
  if (startsWithBegin && endsWithCommit) return "self-contained";
  if (!startsWithBegin && !endsWithCommit) return "wrapped-by-runner";
  throw new Error("MIGRATION_TRANSACTION_BOUNDARY_INVALID");
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function listMigrations() {
  const excluded = new Set(policy.database?.excludedForwardMigrations || []);
  return fs.readdirSync(migrationRoot, { withFileTypes: true })
    .filter((entry) => entry.isFile() && CANONICAL_MIGRATION_FILE.test(entry.name) && !excluded.has(entry.name))
    .map((entry) => {
      const match = CANONICAL_MIGRATION_FILE.exec(entry.name);
      const sql = fs.readFileSync(path.join(migrationRoot, entry.name));
      return {
        version: match[1],
        slug: match[2],
        name: entry.name,
        sha256: sha256(sql),
        bytes: sql.byteLength,
        transactionMode: transactionMode(sql.toString("utf8")),
      };
    })
    .sort((left, right) => left.version.localeCompare(right.version));
}

function manifestFor(migrations) {
  const core = {
    schemaVersion: 1,
    projectId: policy.projectId || "zimeiti-caopanshou",
    migrationRoot: (policy.database?.migrationRoot || "supabase/migrations").replaceAll("\\", "/"),
    excludedForwardMigrations: [...(policy.database?.excludedForwardMigrations || [])].sort(),
    migrationCount: migrations.length,
    totalBytes: migrations.reduce((sum, item) => sum + item.bytes, 0),
    migrations: migrations.map(({ version, name, sha256: hash, transactionMode: mode }) => ({
      version,
      name,
      sha256: hash,
      transactionMode: mode,
    })),
  };
  return { ...core, manifestSha256: sha256(stableJson(core)) };
}

function renderSql(migrations, manifest, contract) {
  const values = migrations.map((migration) => `  (${[
    sqlLiteral(migration.version),
    sqlLiteral(migration.slug),
    sqlLiteral(migration.name),
    sqlLiteral(migration.sha256),
  ].join(", ")})`).join(",\n");
  return `-- Generated by scripts/render-migration-ledger-reconciliation.mjs. Do not edit by hand.
-- Migration SQL is not replayed. This only adopts an already verified final schema into the release ledger.
-- migration-manifest-sha256: ${manifest.manifestSha256}
-- semantic-contract-sha256: ${contract.contractSha256}
-- semantic-snapshot-sha256: ${contract.snapshot.sha256}

BEGIN;

SELECT pg_advisory_xact_lock(260830500012);

DO $target_guard$
DECLARE
  expected_database text := current_setting('zimeiti.expected_database', true);
BEGIN
  IF COALESCE(expected_database, '') = '' THEN
    RAISE EXCEPTION 'LEDGER_RECONCILIATION_EXPECTED_DATABASE_REQUIRED';
  END IF;
  IF current_database() IS DISTINCT FROM expected_database THEN
    RAISE EXCEPTION 'LEDGER_RECONCILIATION_TARGET_MISMATCH expected=% actual=%', expected_database, current_database();
  END IF;
END
$target_guard$;

CREATE SCHEMA IF NOT EXISTS supabase_migrations;
CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (
  version text PRIMARY KEY,
  name text,
  statements text[],
  hash text,
  applied_by text,
  applied_at timestamptz NOT NULL DEFAULT now()
);

DO $legacy_shape$
DECLARE
  statements_type text;
BEGIN
  SELECT format_type(attribute.atttypid, attribute.atttypmod)
    INTO statements_type
    FROM pg_attribute AS attribute
    JOIN pg_class AS relation ON relation.oid = attribute.attrelid
    JOIN pg_namespace AS namespace ON namespace.oid = relation.relnamespace
   WHERE namespace.nspname = 'supabase_migrations'
     AND relation.relname = 'schema_migrations'
     AND attribute.attname = 'statements'
     AND attribute.attnum > 0
     AND NOT attribute.attisdropped;

  IF statements_type IS NOT NULL AND statements_type <> 'text[]' THEN
    IF EXISTS (
      SELECT 1
        FROM information_schema.columns
       WHERE table_schema = 'supabase_migrations'
         AND table_name = 'schema_migrations'
         AND column_name = 'legacy_statements'
    ) THEN
      RAISE EXCEPTION 'LEDGER_RECONCILIATION_LEGACY_STATEMENTS_CONFLICT';
    END IF;
    ALTER TABLE supabase_migrations.schema_migrations RENAME COLUMN statements TO legacy_statements;
  END IF;
END
$legacy_shape$;

DO $legacy_nullability$
BEGIN
  IF EXISTS (
    SELECT 1
      FROM information_schema.columns
     WHERE table_schema = 'supabase_migrations'
       AND table_name = 'schema_migrations'
       AND column_name = 'legacy_statements'
  ) THEN
    ALTER TABLE supabase_migrations.schema_migrations
      ALTER COLUMN legacy_statements DROP NOT NULL;
  END IF;
END
$legacy_nullability$;

ALTER TABLE supabase_migrations.schema_migrations ADD COLUMN IF NOT EXISTS name text;
ALTER TABLE supabase_migrations.schema_migrations ADD COLUMN IF NOT EXISTS statements text[];
ALTER TABLE supabase_migrations.schema_migrations ADD COLUMN IF NOT EXISTS hash text;
ALTER TABLE supabase_migrations.schema_migrations ADD COLUMN IF NOT EXISTS applied_by text;
ALTER TABLE supabase_migrations.schema_migrations ADD COLUMN IF NOT EXISTS applied_at timestamptz NOT NULL DEFAULT now();

CREATE TEMP TABLE zimeiti_expected_migrations (
  version text PRIMARY KEY,
  slug text NOT NULL,
  filename text NOT NULL,
  sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$')
) ON COMMIT DROP;

INSERT INTO zimeiti_expected_migrations(version, slug, filename, sha256) VALUES
${values};

DO $hash_guard$
DECLARE
  drift_versions text;
BEGIN
  SELECT string_agg(actual.version, ',' ORDER BY actual.version)
    INTO drift_versions
    FROM supabase_migrations.schema_migrations AS actual
    JOIN zimeiti_expected_migrations AS expected USING (version)
   WHERE COALESCE(actual.hash, '') <> ''
     AND lower(actual.hash) <> expected.sha256;
  IF drift_versions IS NOT NULL THEN
    RAISE EXCEPTION 'LEDGER_RECONCILIATION_HASH_DRIFT versions=%', drift_versions;
  END IF;
END
$hash_guard$;

INSERT INTO supabase_migrations.schema_migrations
  (version, name, statements, hash, applied_by, applied_at)
SELECT version, slug, ARRAY[filename], sha256,
       'codex-release:verified-semantic-ledger-reconciliation', now()
  FROM zimeiti_expected_migrations
ON CONFLICT (version) DO UPDATE
  SET name = CASE
        WHEN COALESCE(supabase_migrations.schema_migrations.name, '') = '' THEN EXCLUDED.name
        ELSE supabase_migrations.schema_migrations.name
      END,
      statements = EXCLUDED.statements,
      hash = EXCLUDED.hash,
      applied_by = COALESCE(
        supabase_migrations.schema_migrations.applied_by,
        'codex-release:verified-semantic-ledger-reconciliation'
      ),
      applied_at = COALESCE(supabase_migrations.schema_migrations.applied_at, now());

DO $post_guard$
DECLARE
  missing_or_drifted integer;
BEGIN
  SELECT count(*)
    INTO missing_or_drifted
    FROM zimeiti_expected_migrations AS expected
    LEFT JOIN supabase_migrations.schema_migrations AS actual USING (version)
   WHERE actual.version IS NULL OR lower(COALESCE(actual.hash, '')) <> expected.sha256;
  IF missing_or_drifted <> 0 THEN
    RAISE EXCEPTION 'LEDGER_RECONCILIATION_POSTCHECK_FAILED count=%', missing_or_drifted;
  END IF;
END
$post_guard$;

COMMIT;
`;
}

const migrations = listMigrations();
const manifest = manifestFor(migrations);
const contract = JSON.parse(fs.readFileSync(contractPath, "utf8"));
if (contract.migrationManifestSha256 !== manifest.manifestSha256) {
  throw new Error("SEMANTIC_CONTRACT_MIGRATION_MANIFEST_MISMATCH");
}
if (!/^[a-f0-9]{64}$/u.test(contract.contractSha256 || "") || !/^[a-f0-9]{64}$/u.test(contract.snapshot?.sha256 || "")) {
  throw new Error("SEMANTIC_CONTRACT_DIGEST_INVALID");
}
const rendered = renderSql(migrations, manifest, contract);

if (write) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, rendered, "utf8");
} else if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== rendered) {
  throw new Error("MIGRATION_LEDGER_RECONCILIATION_ARTIFACT_STALE");
}

console.log(JSON.stringify({
  ok: true,
  mode: write ? "write" : "verify",
  artifact: path.relative(root, outputPath).split(path.sep).join("/"),
  artifactSha256: sha256(rendered),
  migrationManifestSha256: manifest.manifestSha256,
  semanticContractSha256: contract.contractSha256,
  semanticSnapshotSha256: contract.snapshot.sha256,
  migrationCount: migrations.length,
  databaseWrites: 0,
  paidModelCalls: 0,
  credentialsPrinted: false,
}, null, 2));
