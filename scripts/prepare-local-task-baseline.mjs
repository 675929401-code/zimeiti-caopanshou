#!/usr/bin/env node
// Build a NEW local database baseline from schema metadata, never from business rows.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = path.join(root, '.codex-evidence/local-data-bootstrap-20260902/schema-source.json');
const destination = path.join(root, 'deploy/local/task-baseline.sql');
const raw = fs.readFileSync(input);
const { definitions } = JSON.parse(raw.toString('utf8'));
const types = new Set(['uuid', 'character varying', 'text', 'numeric', 'boolean', 'integer', 'bigint', 'smallint', 'timestamp with time zone', 'jsonb', 'text[]']);
const ident = value => {
  if (!/^[a-z][a-z0-9_]*$/u.test(value)) throw new Error('Unexpected schema identifier');
  return `"${value}"`;
};
const literal = value => `'${String(value).replaceAll("'", "''")}'`;
const sql = [
  '-- NEW LOCAL DATABASE ONLY. No imported users, balances, chats or generation history.',
  `-- Source column/default/PK/FK metadata SHA256: ${createHash('sha256').update(raw).digest('hex')}`,
  '-- Application-required unique constraints are explicit below; this is not a production backup.',
  'BEGIN;',
  "DO $$ BEGIN IF current_database() <> 'zimeiti_local' OR inet_server_addr() <> '127.0.0.1'::inet THEN RAISE EXCEPTION 'LOCAL_DATABASE_ONLY'; END IF; END $$;",
  "DO $$ BEGIN IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE') THEN RAISE EXCEPTION 'LOCAL_BASELINE_REQUIRES_EMPTY_DATABASE'; END IF; END $$;",
  'GRANT USAGE ON SCHEMA public TO service_role, anon, authenticated;',
];
const relations = [];
for (const [table, definition] of Object.entries(definitions)) {
  const required = new Set(definition.required || []);
  const primary = Object.entries(definition.properties).filter(([, prop]) => prop.description?.includes('<pk/>')).map(([column]) => column);
  const columns = Object.entries(definition.properties).map(([column, prop]) => {
    if (!types.has(prop.format)) throw new Error(`Unsupported type for ${table}.${column}`);
    let type = prop.format;
    if (type === 'character varying' && Number.isInteger(prop.maxLength)) type += `(${prop.maxLength})`;
    let suffix = '';
    if (primary.includes(column) && ['integer', 'bigint', 'smallint'].includes(type)) {
      suffix = ' GENERATED BY DEFAULT AS IDENTITY';
    } else if ('default' in prop) {
      const value = prop.default;
      let expression;
      if (value === null || value === 'NULL') expression = 'NULL';
      else if (typeof value === 'number' && Number.isFinite(value)) expression = String(value);
      else if (typeof value === 'boolean') expression = value ? 'true' : 'false';
      else if (typeof value === 'string' && value.includes('gen_random_uuid()')) expression = prop.format === 'uuid' ? 'gen_random_uuid()' : 'gen_random_uuid()::text';
      else if (value === 'now()') expression = 'now()';
      else if (value === "(now() + '7 days'::interval)") expression = "(now() + interval '7 days')";
      else if (primary.includes(column) && typeof value === 'string' && value.startsWith('(((')) expression = 'gen_random_uuid()::text';
      else if (prop.format === 'jsonb') expression = `${literal(JSON.stringify(value))}::jsonb`;
      else expression = literal(value);
      suffix += ` DEFAULT ${expression}`;
    }
    if (required.has(column)) suffix += ' NOT NULL';
    const foreign = /<fk table='([a-z0-9_]+)' column='([a-z0-9_]+)'\/>/u.exec(prop.description || '');
    if (foreign) relations.push({ table, column, target: foreign[1], targetColumn: foreign[2] });
    return `  ${ident(column)} ${type}${suffix}`;
  });
  if (primary.length) columns.push(`  PRIMARY KEY (${primary.map(ident).join(', ')})`);
  sql.push(`CREATE TABLE public.${ident(table)} (\n${columns.join(',\n')}\n);`);
}
for (const relation of relations) {
  sql.push(`ALTER TABLE public.${ident(relation.table)} ADD FOREIGN KEY (${ident(relation.column)}) REFERENCES public.${ident(relation.target)} (${ident(relation.targetColumn)}) DEFERRABLE INITIALLY DEFERRED;`);
}
for (const [table, columns] of [['users', ['username']], ['platform_settings', ['setting_key']], ['agent_skills', ['agent_id', 'skill_id']]]) {
  sql.push(`CREATE UNIQUE INDEX ${ident(`local_${table}_${columns.join('_')}_unique`)} ON public.${ident(table)} (${columns.map(ident).join(', ')});`);
}
sql.push('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO service_role;');
sql.push('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;');
sql.push('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, anon, authenticated;');
for (const table of Object.keys(definitions)) {
  sql.push(`ALTER TABLE public.${ident(table)} ENABLE ROW LEVEL SECURITY;`);
  sql.push(`CREATE POLICY local_service_access ON public.${ident(table)} FOR ALL TO service_role USING (true) WITH CHECK (true);`);
}
sql.push('COMMIT;');
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, `${sql.join('\n\n')}\n`);
console.log(JSON.stringify({ tables: Object.keys(definitions).length, foreignKeys: relations.length, output: path.relative(root, destination), includesBusinessRows: false }));
