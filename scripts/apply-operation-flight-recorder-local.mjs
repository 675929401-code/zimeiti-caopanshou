#!/usr/bin/env node
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import pg from "pg";

const VERSION = "20261001020000";
const NAME = "operation_flight_recorder";
const MIGRATION_FILE = `${VERSION}_${NAME}.sql`;
const SEQUENCE_VERSION = "20261001030000";
const SEQUENCE_NAME = "operation_flight_recorder_sequence";
const SEQUENCE_MIGRATION_FILE = `${SEQUENCE_VERSION}_${SEQUENCE_NAME}.sql`;
const RUNTIME_FILE = process.env.LOCAL_ACCEPTANCE_RUNTIME_PATH?.trim()
  || "F:/总项目文件/Skill存储系统/运行数据/自媒体操盘手/local-data-20260902/config/runtime.json";

assert.ok(process.argv.includes("--execute"), "EXPLICIT_EXECUTION_REQUIRED");
assert.ok(process.argv.includes("--confirm-local-flight-recorder"), "LOCAL_FLIGHT_RECORDER_CONFIRMATION_REQUIRED");

const runtime = JSON.parse((await fs.readFile(RUNTIME_FILE, "utf8")).replace(/^\uFEFF/u, ""));
assert.equal(runtime.localOnly, true, "LOCAL_RUNTIME_REQUIRED");
assert.equal(runtime.ownerConnection?.host, "127.0.0.1", "LOCAL_DATABASE_HOST_REQUIRED");
assert.equal(Number(runtime.ownerConnection?.port), 54322, "LOCAL_DATABASE_PORT_REQUIRED");
assert.equal(runtime.ownerConnection?.database, "zimeiti_local", "LOCAL_DATABASE_NAME_REQUIRED");

const migrationPath = path.resolve("supabase/migrations", MIGRATION_FILE);
const source = await fs.readFile(migrationPath, "utf8");
const normalized = source.replace(/^\uFEFF/u, "").trim();
assert.match(normalized, /^BEGIN\s*;/u, "MIGRATION_BEGIN_REQUIRED");
assert.match(normalized, /COMMIT\s*;\s*$/u, "MIGRATION_COMMIT_REQUIRED");
assert.match(normalized, /CREATE TABLE IF NOT EXISTS public\.operation_flight_events/u);
assert.match(normalized, /CREATE OR REPLACE FUNCTION public\.capture_operation_flight_event/u);
assert.match(normalized, /Telemetry can never make a paid or user-facing business transaction fail/u);
assert.doesNotMatch(normalized, /prompt\s*(?:text|body)|response_body\s*[,)]/iu, "SENSITIVE_PAYLOAD_COLUMN_FORBIDDEN");
const body = normalized.replace(/^BEGIN\s*;/u, "").replace(/COMMIT\s*;\s*$/u, "").trim();
const migrationHash = crypto.createHash("sha256").update(source).digest("hex");
const sequenceMigrationPath = path.resolve("supabase/migrations", SEQUENCE_MIGRATION_FILE);
const sequenceSource = await fs.readFile(sequenceMigrationPath, "utf8");
const sequenceNormalized = sequenceSource.replace(/^\uFEFF/u, "").trim();
assert.match(sequenceNormalized, /^BEGIN\s*;/u, "SEQUENCE_MIGRATION_BEGIN_REQUIRED");
assert.match(sequenceNormalized, /COMMIT\s*;\s*$/u, "SEQUENCE_MIGRATION_COMMIT_REQUIRED");
assert.match(sequenceNormalized, /capture_sequence bigint GENERATED BY DEFAULT AS IDENTITY/u);
const sequenceBody = sequenceNormalized.replace(/^BEGIN\s*;/u, "").replace(/COMMIT\s*;\s*$/u, "").trim();
const sequenceMigrationHash = crypto.createHash("sha256").update(sequenceSource).digest("hex");

const client = new pg.Client({
  ...runtime.ownerConnection,
  application_name: "codex-local-operation-flight-recorder",
  connectionTimeoutMillis: 10_000,
  query_timeout: 120_000,
});

await client.connect();
let transactionOpen = false;
try {
  const identity = (await client.query(
    "SELECT current_database() AS database_name, inet_server_addr()::text AS server_address, inet_server_port() AS server_port",
  )).rows[0];
  assert.equal(identity.database_name, "zimeiti_local", "LIVE_DATABASE_NAME_MISMATCH");
  assert.equal(Number(identity.server_port), 54322, "LIVE_DATABASE_PORT_MISMATCH");

  await client.query("BEGIN");
  transactionOpen = true;
  await client.query("SELECT pg_advisory_xact_lock(hashtextextended('operation-flight-recorder:20261001020000',0))");
  assert.equal((await client.query("SELECT to_regclass('supabase_migrations.schema_migrations')::text AS name")).rows[0]?.name, "supabase_migrations.schema_migrations", "MIGRATION_LEDGER_REQUIRED");
  const prior = await client.query(
    "SELECT version,hash FROM supabase_migrations.schema_migrations WHERE version::text=$1",
    [VERSION],
  );
  let action = "already_applied";
  if (prior.rowCount) {
    assert.equal(String(prior.rows[0].hash || ""), migrationHash, "MIGRATION_LEDGER_HASH_CONFLICT");
  } else {
    await client.query(body);
    await client.query(
      `INSERT INTO supabase_migrations.schema_migrations(version,name,statements,hash,applied_by,applied_at)
       VALUES($1,$2,$3,$4,$5,now())`,
      [VERSION, NAME, [MIGRATION_FILE], migrationHash, "codex-local-flight-recorder"],
    );
    action = "applied";
  }
  const priorSequence = await client.query(
    "SELECT version,hash FROM supabase_migrations.schema_migrations WHERE version::text=$1",
    [SEQUENCE_VERSION],
  );
  let sequenceAction = "already_applied";
  if (priorSequence.rowCount) {
    assert.equal(String(priorSequence.rows[0].hash || ""), sequenceMigrationHash, "SEQUENCE_MIGRATION_LEDGER_HASH_CONFLICT");
  } else {
    await client.query(sequenceBody);
    await client.query(
      `INSERT INTO supabase_migrations.schema_migrations(version,name,statements,hash,applied_by,applied_at)
       VALUES($1,$2,$3,$4,$5,now())`,
      [SEQUENCE_VERSION, SEQUENCE_NAME, [SEQUENCE_MIGRATION_FILE], sequenceMigrationHash, "codex-local-flight-recorder"],
    );
    sequenceAction = "applied";
  }
  await client.query("NOTIFY pgrst, 'reload schema'");
  await client.query("COMMIT");
  transactionOpen = false;

  const columns = await client.query(
    `SELECT column_name FROM information_schema.columns
      WHERE table_schema='public' AND table_name='operation_flight_events'`,
  );
  const columnNames = new Set(columns.rows.map((row) => row.column_name));
  for (const required of ["trace_id", "source", "domain", "operation", "phase", "outcome", "duration_ms", "metadata", "source_version", "build_id"]) {
    assert.ok(columnNames.has(required), `FLIGHT_COLUMN_MISSING:${required}`);
  }
  const triggerRows = await client.query(
    `SELECT DISTINCT event_object_table
       FROM information_schema.triggers
      WHERE trigger_schema='public' AND trigger_name='operation_flight_recorder'
      ORDER BY event_object_table`,
  );
  const expectedTables = ["extraction_attempts", "image_generation_requests", "llm_request_attempts", "video_tasks", "voice_generation_requests"];
  assert.deepEqual(triggerRows.rows.map((row) => row.event_object_table), expectedTables, "LIFECYCLE_TRIGGER_COVERAGE_MISMATCH");

  const fixtureRecord = crypto.createHash("sha256").update(`flight-recorder:${Date.now()}`).digest("hex");
  const fixtureRequest = `flight-recorder-${crypto.randomUUID()}`;
  await client.query("BEGIN");
  transactionOpen = true;
  await client.query(
    `INSERT INTO public.extraction_attempts(record_id,user_id,client_request_id,request_kind,payload_fingerprint,state)
     VALUES($1,$2,$3,'single',$4,'running')`,
    [fixtureRecord, "flight-recorder-fixture-user", fixtureRequest, crypto.createHash("sha256").update("fixture-payload").digest("hex")],
  );
  await client.query(
    `UPDATE public.extraction_attempts
        SET state='failed',http_status=502,response='{"error":"fixture"}'::jsonb,error_code='FIXTURE_UPSTREAM',error_message='must-not-enter-flight-log',updated_at=now()
      WHERE record_id=$1`,
    [fixtureRecord],
  );
  const fixtureEvents = await client.query(
    `SELECT trace_id,source,domain,phase,outcome,http_status,error_code,metadata::text AS metadata
       FROM public.operation_flight_events WHERE trace_id=$1 ORDER BY capture_sequence`,
    [fixtureRequest],
  );
  assert.equal(fixtureEvents.rowCount, 2, "FIXTURE_EVENT_COUNT_MISMATCH");
  assert.deepEqual(fixtureEvents.rows.map((row) => row.phase), ["running", "failed"]);
  assert.deepEqual(fixtureEvents.rows.map((row) => row.outcome), ["in_progress", "error"]);
  assert.ok(fixtureEvents.rows.every((row) => row.source === "database" && row.domain === "extract"));
  assert.ok(fixtureEvents.rows.every((row) => !row.metadata.includes("must-not-enter-flight-log") && !row.metadata.includes("fixture-payload")), "SENSITIVE_FIXTURE_DATA_LEAKED");
  await client.query("ROLLBACK");
  transactionOpen = false;

  const report = {
    passed: true,
    checkedAt: new Date().toISOString(),
    target: "127.0.0.1:54322/zimeiti_local",
    migrations: [
      { file: MIGRATION_FILE, hash: migrationHash, action },
      { file: SEQUENCE_MIGRATION_FILE, hash: sequenceMigrationHash, action: sequenceAction },
    ],
    triggerTables: expectedTables,
    fixture: { eventCount: 2, phases: ["running", "failed"], residue: 0 },
    productionWrites: 0,
    credentialsPrinted: false,
  };
  const evidenceDir = path.resolve(".codex-evidence", "operation-flight-recorder");
  await fs.mkdir(evidenceDir, { recursive: true });
  await fs.writeFile(path.join(evidenceDir, "migration.json"), `${JSON.stringify(report, null, 2)}\n`, "utf8");
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  if (transactionOpen) await client.query("ROLLBACK").catch(() => undefined);
  throw error;
} finally {
  await client.end();
}
