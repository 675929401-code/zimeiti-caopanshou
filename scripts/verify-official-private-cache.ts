import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { officialPrivateCacheKey, readOfficialPrivateCache, writeOfficialPrivateCache } from "@/lib/official-agent-private-cache";

const values = new Map<string, string>([["xuefeng-user-shortcuts", '[{"content":"legacy private"}]'], ["youcai_agent_asset_favorites_v1", '["legacy"]']]);
const reads: string[] = [];
const writes: string[] = [];
const storage = { getItem: (key: string) => { reads.push(key); return values.get(key) ?? null; }, setItem: (key: string, value: string) => { writes.push(key); values.set(key, value); } };
let owner = "user-A";
assert.equal(readOfficialPrivateCache(storage, owner, "prompts").value, null, "unowned global prompts must not be imported");
assert.equal(writeOfficialPrivateCache(storage, owner, "prompts", [{ content: "A private" }], () => owner), true);
assert.deepEqual(readOfficialPrivateCache(storage, owner, "prompts").value, [{ content: "A private" }]);
const delayedAWrite = () => writeOfficialPrivateCache(storage, "user-A", "prompts", [{ content: "delayed A" }], () => owner);
owner = "user-B";
assert.equal(readOfficialPrivateCache(storage, owner, "prompts").value, null);
assert.equal(delayedAWrite(), false);
assert.equal(writeOfficialPrivateCache(storage, owner, "favorites", ["B asset"], () => owner), true);
assert.equal(readOfficialPrivateCache(storage, "user-A", "favorites").value, null);
assert.deepEqual(readOfficialPrivateCache(storage, "user-B", "favorites").value, ["B asset"]);
owner = "";
const beforeLogoutRead = reads.length, beforeLogoutWrite = writes.length;
assert.equal(readOfficialPrivateCache(storage, owner, "prompts").value, null);
assert.equal(delayedAWrite(), false);
assert.equal(writeOfficialPrivateCache(storage, "", "prompts", ["anonymous"], () => owner), false);
assert.equal(reads.length, beforeLogoutRead);
assert.equal(writes.length, beforeLogoutWrite);
owner = "user-A";
const changingValue = { toJSON() { owner = "user-B"; return "A serialized"; } };
assert.equal(writeOfficialPrivateCache(storage, "user-A", "prompts", changingValue, () => owner), false, "owner must still match after serialization");
assert.deepEqual(readOfficialPrivateCache(storage, "user-A", "prompts").value, [{ content: "A private" }]);
assert.equal(officialPrivateCacheKey("../bad-owner", "prompts"), null);
assert.equal(readOfficialPrivateCache({ ...storage, getItem: () => { throw new Error("DENIED"); } }, "user-A", "prompts").ok, false);
assert.equal(writeOfficialPrivateCache({ ...storage, setItem: () => { throw new Error("QUOTA"); } }, "user-B", "favorites", [], () => owner), false);
const draft = { prompt: "准备图生图", referenceName: "产品.png", savedAt: "2026-10-16T00:00:00Z" };
assert.equal(writeOfficialPrivateCache(storage, "user-B", "youcai_tool_draft:/tools/image/image-edit", draft, () => owner), true);
assert.deepEqual(readOfficialPrivateCache(storage, "user-B", "youcai_tool_draft:/tools/image/image-edit").value, draft);
assert.equal(readOfficialPrivateCache(storage, "user-A", "youcai_tool_draft:/tools/image/image-edit").value, null);
assert.ok(reads.every(key => key.startsWith("official-private.v1:")));
assert.equal(values.has("xuefeng-user-shortcuts"), true, "unowned legacy data must not be guessed, migrated or deleted");
values.set(officialPrivateCacheKey("user-B", "broken")!, "bad-json");
assert.equal(readOfficialPrivateCache(storage, "user-B", "broken").ok, false);
const route = readFileSync("src/features/official-core-routes/official-agent-route.tsx", "utf8");
assert.match(route, /privateCacheOwner === privateOwnerId/u);
assert.match(route, /privateOwnerRef\.current !== privateOwnerId/u);
assert.match(route, /promptEditorOpen && privateCacheReady/u);
assert.doesNotMatch(route, /localStorage\.(?:getItem|setItem)\((?:PROMPT_LIBRARY_STORAGE_KEY|ASSET_FAVORITES_STORAGE_KEY)/u);
const alias = readFileSync("src/features/official-tool-aliases/official-tool-alias-page.tsx", "utf8");
assert.match(alias, /readOfficialPrivateCache<unknown>\(window\.sessionStorage, ownerId, draftKey\)/u);
assert.match(alias, /draftOwner === ownerId \? prompt : ""/u);
assert.match(alias, /目标工作台尚不自动导入/u);
console.log(JSON.stringify({ passed: true, ownerIsolation: "A->B->logout", legacyGlobalNotRead: true, delayedWriteBlocked: true, storageFailureHandled: true, scopedSessionDraftRestored: true, zeroNetwork: true }));
