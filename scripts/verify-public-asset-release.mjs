#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const LOCAL_VERIFIER_ID = "verify-public-asset-release-local-disk";
const LOCAL_VERIFIER_VERSION = 1;

const allowedOptions = new Set([
  "--root",
  "--policy",
  "--manifest",
  "--asset-root",
  "--write-ready",
  "--storage-backend",
  "--location",
]);
const flagOptions = new Set(["--write-ready"]);
const options = new Map();
for (let index = 2; index < process.argv.length; index += 1) {
  const argument = process.argv[index];
  if (!argument.startsWith("--") || !allowedOptions.has(argument)) {
    console.error(`FAIL unknown or positional option: ${argument}`);
    process.exit(2);
  }
  if (options.has(argument)) {
    console.error(`FAIL duplicate option: ${argument}`);
    process.exit(2);
  }
  if (flagOptions.has(argument)) {
    options.set(argument, "1");
    continue;
  }
  const next = process.argv[index + 1];
  if (!next || next.startsWith("--")) {
    console.error(`FAIL ${argument} requires a value`);
    process.exit(2);
  }
  options.set(argument, next);
  index += 1;
}

function stop(message, code = 1) {
  console.error(`FAIL ${message}`);
  process.exit(code);
}

function normalize(value) {
  return value.replace(/\\/g, "/").replace(/^\.\//u, "").replace(/\/+$/u, "");
}

function isInside(parent, child) {
  const relative = path.relative(parent, child);
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
}

function sha256Buffer(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function sha256File(filePath) {
  const hash = crypto.createHash("sha256");
  const descriptor = fs.openSync(filePath, "r");
  const buffer = Buffer.allocUnsafe(1024 * 1024);
  try {
    while (true) {
      const bytesRead = fs.readSync(descriptor, buffer, 0, buffer.length, null);
      if (!bytesRead) break;
      hash.update(buffer.subarray(0, bytesRead));
    }
  } finally {
    fs.closeSync(descriptor);
  }
  return hash.digest("hex");
}

function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map((entry) => stableJson(entry)).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort((left, right) => left.localeCompare(right, "en"))
      .map((key) => `${JSON.stringify(key)}:${stableJson(value[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function assertNoSymlinkComponents(anchor, target) {
  const resolvedAnchor = path.resolve(anchor);
  const resolvedTarget = path.resolve(target);
  if (!isInside(resolvedAnchor, resolvedTarget)) stop(`path escapes trusted anchor: ${resolvedTarget}`, 2);
  const anchorStats = fs.lstatSync(resolvedAnchor);
  if (!anchorStats.isDirectory() || anchorStats.isSymbolicLink()) stop(`trusted anchor is not a real directory: ${resolvedAnchor}`, 2);
  let current = resolvedAnchor;
  for (const segment of path.relative(resolvedAnchor, resolvedTarget).split(path.sep).filter(Boolean)) {
    current = path.join(current, segment);
    if (!fs.existsSync(current)) stop(`missing path component: ${current}`, 2);
    if (fs.lstatSync(current).isSymbolicLink()) stop(`symbolic links are forbidden: ${current}`, 2);
  }
}

function resolveTrustedFile(root, candidate, label) {
  const resolved = path.resolve(root, candidate);
  if (!isInside(root, resolved)) stop(`${label} must remain inside the project root`, 2);
  assertNoSymlinkComponents(root, resolved);
  const stats = fs.lstatSync(resolved);
  if (!stats.isFile() || stats.isSymbolicLink()) stop(`${label} must be a real file: ${resolved}`, 2);
  return resolved;
}

function validateCanonicalRoot(value, label) {
  if (typeof value !== "string" || value !== normalize(value) || value.includes("\\") || value.includes("\0")) {
    stop(`${label} is not a canonical forward-slash path`, 2);
  }
  const parts = value.split("/");
  if (parts.length < 2 || parts[0] !== "public" || parts.some((part) => !part || part === "." || part === "..")) {
    stop(`${label} is invalid: ${value}`, 2);
  }
  return value;
}

function pathMatchesRoot(relativePath, rootPath) {
  return relativePath === rootPath || relativePath.startsWith(`${rootPath}/`);
}

const storageBackend = options.get("--storage-backend") || "disk";
if (storageBackend !== "disk") {
  stop("local verifier cannot mint or validate COS READY; COS READY must be generated by publish-public-assets-cos-vnext", 2);
}
if (options.get("--write-ready") === "1") {
  stop("--write-ready is disabled: final disk READY may only be signed by install-public-asset-release-vnext after server-side full SHA verification", 2);
}
const projectRoot = path.resolve(options.get("--root") || process.cwd());
if (!fs.existsSync(projectRoot)) stop(`project root does not exist: ${projectRoot}`, 2);
assertNoSymlinkComponents(path.parse(projectRoot).root, projectRoot);
const projectStats = fs.lstatSync(projectRoot);
if (!projectStats.isDirectory() || projectStats.isSymbolicLink()) stop("project root must be a real directory", 2);
const policyPath = resolveTrustedFile(projectRoot, options.get("--policy") || "deploy/policies/release-policy.json", "release policy");
const manifestPath = resolveTrustedFile(projectRoot, options.get("--manifest") || "deploy/manifests/public-assets.v1.json", "asset manifest");
const assetRoot = path.resolve(options.get("--asset-root") || projectRoot);
if (!fs.existsSync(assetRoot)) stop(`asset root does not exist: ${assetRoot}`, 2);
assertNoSymlinkComponents(path.parse(assetRoot).root, assetRoot);
const assetRootStats = fs.lstatSync(assetRoot);
if (!assetRootStats.isDirectory() || assetRootStats.isSymbolicLink()) stop(`asset root must be a real directory: ${assetRoot}`, 2);
const resolvedAssetRoot = fs.realpathSync(assetRoot);
const location = options.get("--location") || resolvedAssetRoot;
if (!location.trim() || path.resolve(location) !== resolvedAssetRoot) {
  stop("local verification location must equal the verified asset root", 2);
}

const policy = JSON.parse(fs.readFileSync(policyPath, "utf8"));
const manifestBytes = fs.readFileSync(manifestPath);
const manifest = JSON.parse(manifestBytes.toString("utf8"));
if (!policy || policy.schemaVersion !== 1 || typeof policy.projectId !== "string" || !policy.assets) {
  stop("release policy identity or assets contract is invalid", 2);
}
const allowedRoots = (policy.assets.externalRoots || []).map((entry, index) => validateCanonicalRoot(entry, `externalRoots[${index}]`));
const forbiddenRoots = (policy.assets.forbiddenPublicRoots || []).map((entry, index) => validateCanonicalRoot(entry, `forbiddenPublicRoots[${index}]`));
if (allowedRoots.length === 0) stop("release policy has no external asset roots", 2);
const assetPolicySha256 = sha256Buffer(Buffer.from(stableJson({
  schemaVersion: policy.schemaVersion,
  projectId: policy.projectId,
  assets: policy.assets,
}), "utf8"));
if (
  !manifest
  || manifest.schemaVersion !== 1
  || manifest.projectId !== policy.projectId
  || manifest.kind !== "public-assets"
  || manifest.contentAddressing !== "sha256-files-and-asset-policy"
  || manifest.mutableUploadsIncluded !== false
  || manifest.assetPolicySha256 !== assetPolicySha256
  || !Array.isArray(manifest.files)
) stop("asset manifest identity or current policy binding is invalid", 2);

let totalBytes = 0;
let previousPath = "";
let canonicalFiles = "";
const exactSeen = new Set();
const portableSeen = new Set();
for (const [index, file] of manifest.files.entries()) {
  const relativePath = String(file?.path || "");
  if (
    relativePath !== normalize(relativePath)
    || relativePath.includes("\\")
    || relativePath.includes("\0")
    || path.posix.isAbsolute(relativePath)
  ) stop(`asset manifest path is not canonical at index ${index}: ${relativePath}`, 2);
  const parts = relativePath.split("/");
  if (parts.some((part) => !part || part === "." || part === "..")) stop(`unsafe asset path segment: ${relativePath}`, 2);
  if (!allowedRoots.some((entry) => pathMatchesRoot(relativePath, entry))) {
    stop(`asset manifest path is outside the production allowlist: ${relativePath}`, 2);
  }
  if (forbiddenRoots.some((entry) => pathMatchesRoot(relativePath, entry))) {
    stop(`asset manifest path is inside a forbidden public root: ${relativePath}`, 2);
  }
  const portableKey = relativePath.toLocaleLowerCase("en");
  if (exactSeen.has(relativePath) || portableSeen.has(portableKey)) stop(`duplicate or portable path collision: ${relativePath}`, 2);
  if (previousPath && previousPath.localeCompare(relativePath, "en") >= 0) stop("asset manifest paths are not canonically sorted", 2);
  if (!Number.isSafeInteger(file.bytes) || file.bytes < 0 || !/^[0-9a-f]{64}$/u.test(String(file.sha256 || ""))) {
    stop(`asset manifest file metadata is invalid: ${relativePath}`, 2);
  }
  const filePath = path.resolve(resolvedAssetRoot, ...parts);
  if (!isInside(resolvedAssetRoot, filePath)) stop(`asset path escapes root: ${relativePath}`, 2);
  assertNoSymlinkComponents(resolvedAssetRoot, filePath);
  const stats = fs.lstatSync(filePath);
  if (!stats.isFile() || stats.isSymbolicLink()) stop(`asset path must be a regular file: ${relativePath}`, 2);
  if (stats.size !== file.bytes) stop(`asset byte size mismatch: ${relativePath}`, 2);
  const digest = sha256File(filePath);
  if (digest !== file.sha256) stop(`asset sha256 mismatch: ${relativePath}`, 2);
  exactSeen.add(relativePath);
  portableSeen.add(portableKey);
  previousPath = relativePath;
  totalBytes += stats.size;
  if (!Number.isSafeInteger(totalBytes)) stop("asset manifest totalBytes exceeds the safe integer range", 2);
  canonicalFiles += `${digest}  ${relativePath}\n`;
}
for (const requiredPath of policy.assets.requiredPaths || []) {
  const canonicalRequired = validateCanonicalRoot(requiredPath, "required asset path");
  if (!exactSeen.has(canonicalRequired)) stop(`required asset is missing from manifest: ${canonicalRequired}`, 2);
}
const digest = sha256Buffer(Buffer.from(`asset-policy-sha256  ${assetPolicySha256}\n${canonicalFiles}`, "utf8"));
if (
  digest !== manifest.digest
  || manifest.assetVersion !== `sha256-${digest}`
  || manifest.fileCount !== manifest.files.length
  || manifest.totalBytes !== totalBytes
) stop("asset manifest digest, count or byte total is invalid", 2);

const manifestSha256 = sha256Buffer(manifestBytes);
const verificationResult = {
  schemaVersion: 1,
  projectId: manifest.projectId,
  kind: "public-assets-verification-result",
  status: "VERIFIED",
  assetVersion: manifest.assetVersion,
  assetDigest: manifest.digest,
  assetPolicySha256,
  manifestSha256,
  fileCount: manifest.fileCount,
  totalBytes: manifest.totalBytes,
  mutableUploadsIncluded: false,
  verificationMode: "full-sha256",
  storageBackend: "disk",
  location: resolvedAssetRoot,
  issuerId: LOCAL_VERIFIER_ID,
  issuerProtocolVersion: LOCAL_VERIFIER_VERSION,
  verifiedAt: new Date().toISOString(),
};
console.log(JSON.stringify({ ok: true, ...verificationResult }, null, 2));
