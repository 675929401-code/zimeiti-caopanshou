/**
 * 获取中文字符串的拼音首字母序列
 * 例如: "爆款文案" → "bkwa"
 * 例如: "同城引流" → "tcyl"
 */
export function getPinyinInitials(text: string): string {
  let initials = '';
  for (const char of text) {
    if (PINYIN_MAP[char]) {
      initials += PINYIN_MAP[char];
    } else if (/[a-zA-Z]/.test(char)) {
      initials += char.toLowerCase();
    } else if (/[0-9]/.test(char)) {
      initials += char;
    }
    // 忽略标点符号等
  }
  return initials;
}

/**
 * 模糊匹配：支持名称搜索和拼音首字母搜索
 * 返回是否匹配以及匹配类型
 */
export function fuzzyMatch(
  name: string,
  query: string
): { matched: boolean; matchType: 'name' | 'pinyin' | 'none' } {
  if (!query) return { matched: true, matchType: 'none' };

  const q = query.toLowerCase();
  const lowerName = name.toLowerCase();

  // 1. 直接名称匹配（包含）
  if (lowerName.includes(q)) {
    return { matched: true, matchType: 'name' };
  }

  // 2. 拼音首字母匹配
  const initials = getPinyinInitials(name);
  if (initials.includes(q)) {
    return { matched: true, matchType: 'pinyin' };
  }

  // 3. 名称中每个词的拼音首字母逐词匹配
  // 例如 "视频带货助手" 查询 "spdh" → 首字母 "spdzs" 包含 "spdh"? 不包含
  // 但如果查 "sphd" 则匹配
  // 我们已经做了完整的首字母序列包含匹配，这已经覆盖了

  return { matched: false, matchType: 'none' };
}
