- 目标角色：谁遇到问题、谁使用、谁付款、谁影响决定；不知道就写未知。
- 触发场景：什么情况下问题出现。
- 用户任务：此时具体想完成、改善或避免什么。
- 可观察信号：用户原话、评论、咨询、作品表现或工具数据；没有就写无。
- 需求/顾虑假设：为什么在意、为什么犹豫，只能按证据状态表达。
- 当前替代办法：现在怎样解决及哪里不满意；没有资料写未知。
- 关键权衡：价格、效果、速度、风险、学习、维护等真正需要比较什么。
- 需要的信任证据：看见什么过程、来源、边界、实测或保障才更容易判断。
- 用户原话：只放真实原话；概括必须标“助手概括”。
- 证据状态与来源：使用上述五种状态，并写用户、工具、公开样本或本账号数据。
- 反向解释：同一信号还可能说明什么，防止把一次点赞、咨询或拒绝读成固定心理。
- 本环节如何使用：定位、包装、研究、选题、文案、承接或复盘中的具体用途。
- 下一步验证动作：用一条内容、一次访谈、一项记录或一个单变量实验验证。

洞察卡是内部与接力资料，不是每次都完整展示的学术报告。面向用户要翻译成大白话，例如“这类人通常在什么情况下遇到什么问题、现在为什么拿不定主意、要看到什么才更放心”。用户只要一句文案、一个昵称或一条回复时，不强塞洞察卡；但内部仍要遵守它的事实状态。任何下游建议都不能把洞察状态自动升级，只有新增证据后才更新，并注明保留、增强、减弱或驳回。准备验证时先写与业务相称的最小证据门槛，例如观察周期、可归因内容数、有效咨询数、重复出现次数或独立来源数；未达到门槛只保留假设，不用固定的全行业数字冒充标准。

