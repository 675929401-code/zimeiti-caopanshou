export type StoryboardAgentConfig = {
  version: string;
  prompt: string;
  updatedAt: string;
};

export function defaultStoryboardAgentConfig(): StoryboardAgentConfig {
  return {
    version: STORYBOARD_AGENT_VERSION,
    prompt: STORYBOARD_AGENT_PROMPT,
    updatedAt: "2026-08-13T00:00:00.000Z",
  };
}

export function parseStoryboardAgentConfig(value: unknown): StoryboardAgentConfig {
  if (typeof value === "string") {
    try {
      return parseStoryboardAgentConfig(JSON.parse(value));
    } catch {
      return defaultStoryboardAgentConfig();
    }
  }
  if (!value || typeof value !== "object") return defaultStoryboardAgentConfig();
  const record = value as Record<string, unknown>;
  const prompt = typeof record.prompt === "string" ? record.prompt.trim() : "";
  if (!prompt) return defaultStoryboardAgentConfig();
  return {
    version: typeof record.version === "string" && record.version.trim() ? record.version.trim() : STORYBOARD_AGENT_VERSION,
    prompt,
    updatedAt: typeof record.updatedAt === "string" ? record.updatedAt : new Date().toISOString(),
  };
}

export function countEffectiveChineseChars(value: string) {
  return Array.from(value).filter((character) => /[\p{L}\p{N}]/u.test(character)).length;
}

export function estimateNarrationSeconds(value: string) {
  return Math.max(5, Math.min(15, Number((countEffectiveChineseChars(value) / 6 + 0.5).toFixed(1))));
}

function splitLongSentence(sentence: string, targetChars: number) {
  const pieces = sentence.split(/(?<=[，、；：])/u).filter(Boolean);
  if (pieces.length === 1) return [sentence];
  const result: string[] = [];
  let current = "";
  for (const piece of pieces) {
    if (current && countEffectiveChineseChars(current + piece) > targetChars + 16) {
      result.push(current);
      current = piece;
    } else {
      current += piece;
    }
  }
  if (current) result.push(current);
  return result;
}

export function segmentNarration(script: string, targetChars = 60) {
  const normalized = script.replace(/\r\n?/g, "\n").replace(/[ \t]+/g, " ").trim();
  const maxChars = targetChars + 15;
  const sentences = normalized
    .split(/(?<=[。！？!?；;\n])/u)
    .flatMap((sentence) => countEffectiveChineseChars(sentence) > targetChars + 20 ? splitLongSentence(sentence, targetChars) : [sentence])
    .map((sentence) => sentence.trim())
    .filter(Boolean);
  if (!sentences.length) return [];

  const segments: string[] = [];
  let current = "";
  for (const sentence of sentences) {
    const combined = current + sentence;
    const combinedCount = countEffectiveChineseChars(combined);
    const currentCount = countEffectiveChineseChars(current);
    if (current && combinedCount > maxChars && currentCount >= Math.max(30, targetChars - 20)) {
      segments.push(current);
      current = sentence;
    } else if (current && combinedCount > maxChars) {
      const clauses = splitLongSentence(sentence, Math.max(20, targetChars - currentCount));
      if (clauses.length > 1) {
        const first = clauses.shift() || "";
        if (countEffectiveChineseChars(current + first) <= maxChars) {
          segments.push(current + first);
          current = clauses.join("");
        } else {
          segments.push(current);
          current = sentence;
        }
      } else {
        segments.push(current);
        current = sentence;
      }
    } else {
      current = combined;
    }
  }
  if (current) segments.push(current);

  if (
    segments.length > 1
    && countEffectiveChineseChars(segments.at(-1) || "") < 24
    && countEffectiveChineseChars((segments.at(-2) || "") + (segments.at(-1) || "")) <= maxChars
  ) {
    const tail = segments.pop() || "";
    segments[segments.length - 1] += tail;
  }
  return segments;
}

export function buildStoryboardUserPrompt(input: {
  script: string;
  style: string;
  ratio: "1:1" | "16:9" | "9:16" | "4:3" | "3:4";
  panelMode: StoryboardPanelMode;
  targetDuration: StoryboardTargetDuration;
  segments: string[];
  textLayoutMode?: StoryboardTextLayoutMode;
}) {
  const fixedSegments = input.segments.map((narration, index) => ({
    order: index + 1,
    narration,
    estimatedSeconds: estimateNarrationSeconds(narration),
  }));
  return `请把以下口播制作成连续的宠物科普故事板项目。

动画风格：${input.style}
成片比例：${input.ratio}
每个生成单元目标时长：${input.targetDuration}秒
故事板格数模式：${input.panelMode}
画面文字模式：${input.textLayoutMode || "visual-only"}
${storyboardTextLayoutInstruction(input.textLayoutMode || "visual-only")}

程序已完成原文保真的语义分段。你不得改变 narration，必须逐字原样返回：
${JSON.stringify(fixedSegments, null, 2)}

原始口播：
${input.script}

严格按系统提示词中的固定JSON格式返回。每个 segments[].durationSeconds 必须等于 ${input.targetDuration}。fixed-4 时每个 segments[].beats 必须恰好4个对象；fixed-5 时必须恰好5个对象；auto 时允许4个或5个对象。`;
}

export function formatStoryboardTxt(project: StoryboardProject) {
  const lines = [
    `# ${project.title}`,
    `版本：${project.version}`,
    `统一风格：${project.styleBible}`,
    `角色锁定：${project.characterBible}`,
    `环境锁定：${project.environmentBible}`,
  ];
  for (const segment of project.segments) {
    lines.push(
      "",
      `## 片段 ${String(segment.order).padStart(2, "0")} · ${segment.durationSeconds}秒`,
      `口播：${segment.narration}`,
      segment.analysisBrief ? `多维拆解：${segment.analysisBrief}` : "",
      "",
      "### 图生视频提示词",
      "```text",
      segment.videoPrompt,
      "```",
      "",
      "### 故事板生图提示词",
      "```text",
      segment.storyboardImagePrompt,
      "```",
    );
  }
  return lines.join("\n");
}
