export const StoryboardBeatSchema = z.object({
  order: z.number().int().min(1).max(5),
  timeRange: z.string().trim().min(3).max(24),
  shotSize: z.string().trim().min(1).max(40),
  visual: z.string().trim().min(12).max(500),
  action: z.string().trim().min(4).max(240),
  semanticEffect: z.string().trim().max(240).default("无"),
  transition: z.string().trim().min(2).max(120),
  videoPrompt: z.string().trim().min(30).max(800),
});

export const StoryboardSegmentSchema = z.object({
  order: z.number().int().min(1).max(80),
  narration: z.string().trim().min(1).max(500),
  durationSeconds: StoryboardTargetDurationSchema,
  storyGoal: z.string().trim().min(6).max(260),
  continuityIn: z.string().trim().max(240).default("开场"),
  continuityOut: z.string().trim().max(240).default("自然落幅"),
  analysisBrief: z.string().trim().max(1200).default(""),
  beats: z.array(StoryboardBeatSchema).min(4).max(5),
  storyboardImagePrompt: z.string().trim().min(120).max(8000),
  videoPrompt: z.string().trim().max(7000).optional().default(""),
  qualityChecklist: z.array(z.string().trim().min(2).max(160)).min(3).max(8),
}).superRefine((segment, context) => {
  const orders = segment.beats.map((beat) => beat.order);
  const expected = segment.beats.map((_, index) => index + 1);
  if (orders.some((order, index) => order !== expected[index])) {
    context.addIssue({
      code: z.ZodIssueCode.custom,
      path: ["beats"],
      message: `分格编号必须严格连续为 ${expected.join("、")}`,
    });
  }
});

