-- Preserve exactly-once semantics while allowing an administrator to close a
-- proven terminal provider rejection. Generic transport failures remain unknown.
BEGIN;

CREATE TABLE IF NOT EXISTS public.image_model_validation_reconciliation_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  validation_id text NOT NULL REFERENCES public.image_model_validations(validation_id),
  image_record_id text NOT NULL REFERENCES public.image_generation_requests(record_id),
  model_id text NOT NULL REFERENCES public.cover_models(id),
  actor_user_id text NOT NULL,
  from_validation_state text NOT NULL CHECK (from_validation_state IN ('claimed','unknown')),
  from_request_state text NOT NULL CHECK (from_request_state = 'failed_unknown'),
  rejection_code text NOT NULL CHECK (rejection_code IN ('IMAGE_UPSTREAM_TERMINAL_EVENT','IMAGE_UPSTREAM_ACCOUNT_UNAVAILABLE')),
  rejection_http_status integer,
  reason text NOT NULL CHECK (char_length(reason) BETWEEN 8 AND 500),
  evidence_ref text NOT NULL CHECK (char_length(evidence_ref) BETWEEN 8 AND 500),
  provider_evidence jsonb NOT NULL CHECK (jsonb_typeof(provider_evidence) = 'object'),
  billing_evidence jsonb NOT NULL CHECK (jsonb_typeof(billing_evidence) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT image_validation_reconciliation_terminal_pair CHECK (
    (rejection_code = 'IMAGE_UPSTREAM_TERMINAL_EVENT' AND rejection_http_status IS NULL)
    OR (rejection_code = 'IMAGE_UPSTREAM_ACCOUNT_UNAVAILABLE' AND rejection_http_status = 503)
  )
);

CREATE INDEX IF NOT EXISTS image_model_validation_reconciliation_validation_idx
  ON public.image_model_validation_reconciliation_audit(validation_id, created_at DESC);

ALTER TABLE public.image_model_validation_reconciliation_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.image_model_validation_reconciliation_audit FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.image_model_validation_reconciliation_audit TO service_role;

CREATE OR REPLACE FUNCTION public.reconcile_image_model_validation_rejection(
  p_validation_id text,
  p_user_id text,
  p_expected_validation_updated_at timestamptz,
  p_expected_request_updated_at timestamptz,
  p_rejection_code text,
  p_http_status integer DEFAULT NULL,
  p_reason text DEFAULT NULL,
  p_evidence_ref text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_validation public.image_model_validations%ROWTYPE;
  v_request public.image_generation_requests%ROWTYPE;
  v_from_validation_state text;
  v_billing_key text;
  v_wallet_operations integer;
  v_wallet_entries integer;
  v_cash_transactions integer;
  v_cash_debts integer;
  v_audit_id bigint;
  v_reason text := trim(coalesce(p_reason, ''));
  v_evidence_ref text := trim(coalesce(p_evidence_ref, ''));
BEGIN
  PERFORM public.assert_image_validation_admin(p_user_id);
  IF p_validation_id !~ '^ivc_[a-f0-9]{64}$'
     OR char_length(v_reason) NOT BETWEEN 8 AND 500
     OR char_length(v_evidence_ref) NOT BETWEEN 8 AND 500
     OR p_rejection_code NOT IN ('IMAGE_UPSTREAM_TERMINAL_EVENT','IMAGE_UPSTREAM_ACCOUNT_UNAVAILABLE')
     OR (p_rejection_code = 'IMAGE_UPSTREAM_TERMINAL_EVENT' AND p_http_status IS NOT NULL)
     OR (p_rejection_code = 'IMAGE_UPSTREAM_ACCOUNT_UNAVAILABLE' AND p_http_status IS DISTINCT FROM 503) THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(p_validation_id, 0));
  SELECT * INTO v_validation
    FROM public.image_model_validations
   WHERE validation_id = p_validation_id
   FOR UPDATE;
  IF NOT FOUND OR v_validation.user_id <> p_user_id THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_OWNER_MISMATCH' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO v_request
    FROM public.image_generation_requests
   WHERE record_id = v_validation.image_record_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_REQUEST_MISSING' USING ERRCODE = 'P0002';
  END IF;
  IF v_validation.state NOT IN ('claimed','unknown') OR v_request.state <> 'failed_unknown' THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_ALREADY_TERMINAL' USING ERRCODE = '22023';
  END IF;
  IF p_expected_validation_updated_at IS NULL OR p_expected_request_updated_at IS NULL
     OR v_validation.updated_at <> p_expected_validation_updated_at
     OR v_request.updated_at <> p_expected_request_updated_at THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_STALE' USING ERRCODE = '40001';
  END IF;
  IF v_request.updated_at > now() - interval '5 minutes' THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_ATTEMPT_ACTIVE' USING ERRCODE = '55000';
  END IF;
  IF v_request.user_id <> v_validation.user_id
     OR v_request.client_idempotency_key <> v_validation.client_idempotency_key
     OR v_request.client_trace_id <> v_validation.client_trace_id
     OR v_request.payload_fingerprint <> v_validation.payload_fingerprint
     OR v_request.response IS NOT NULL
     OR coalesce(v_request.delivery_state, 'held') <> 'held'
     OR v_request.delivery_asset_id IS NOT NULL
     OR v_validation.asset_id IS NOT NULL THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_PROVIDER_OR_ASSET_EVIDENCE_EXISTS' USING ERRCODE = '22023';
  END IF;

  v_billing_key := 'image:h3_' || substr(encode(sha256(convert_to(
    v_validation.user_id || ':' || v_validation.client_idempotency_key, 'UTF8'
  )), 'hex'), 1, 48);
  SELECT count(*)::integer INTO v_wallet_operations
    FROM public.wallet_operations WHERE user_id::text = v_validation.user_id AND idempotency_key = v_billing_key;
  SELECT count(*)::integer INTO v_wallet_entries
    FROM public.wallet_ledger_entries WHERE user_id::text = v_validation.user_id AND idempotency_key = v_billing_key;
  SELECT count(*)::integer INTO v_cash_transactions
    FROM public.cash_transactions WHERE user_id::text = v_validation.user_id AND reference_id = v_billing_key;
  SELECT count(*)::integer INTO v_cash_debts
    FROM public.cash_debt_records WHERE user_id::text = v_validation.user_id AND reference_id = v_billing_key;
  IF v_wallet_operations <> 0 OR v_wallet_entries <> 0 OR v_cash_transactions <> 0 OR v_cash_debts <> 0 THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RECONCILIATION_BILLING_EVIDENCE_EXISTS' USING ERRCODE = '22023';
  END IF;

  v_from_validation_state := v_validation.state;
  UPDATE public.image_generation_requests
     SET response = jsonb_strip_nulls(jsonb_build_object(
           'schema', 'image_request_rejection.v1',
           'payloadFingerprint', v_validation.payload_fingerprint,
           'source', 'provider',
           'code', p_rejection_code,
           'upstreamStatus', p_http_status
         )),
         updated_at = now()
   WHERE record_id = v_request.record_id;
  UPDATE public.image_model_validations
     SET state = 'rejected', rejection_code = p_rejection_code,
         rejection_http_status = p_http_status, updated_at = now()
   WHERE validation_id = v_validation.validation_id
   RETURNING * INTO v_validation;

  INSERT INTO public.image_model_validation_reconciliation_audit(
    validation_id, image_record_id, model_id, actor_user_id,
    from_validation_state, from_request_state, rejection_code,
    rejection_http_status, reason, evidence_ref, provider_evidence, billing_evidence
  ) VALUES (
    v_validation.validation_id, v_request.record_id, v_validation.model_id, p_user_id,
    v_from_validation_state, v_request.state, p_rejection_code,
    p_http_status, v_reason, v_evidence_ref,
    jsonb_build_object('requestState', v_request.state, 'responseWasNull', true,
      'deliveryState', coalesce(v_request.delivery_state, 'held'), 'assetPresent', false,
      'providerCheckpointPresent', false),
    jsonb_build_object('walletOperations', v_wallet_operations, 'walletEntries', v_wallet_entries,
      'cashTransactions', v_cash_transactions, 'cashDebts', v_cash_debts)
  ) RETURNING id INTO v_audit_id;

  RETURN jsonb_build_object('record', to_jsonb(v_validation), 'auditId', v_audit_id);
END;
$$;

-- Called only after the exactly-once store has persisted a bound rejection receipt.
CREATE OR REPLACE FUNCTION public.record_image_model_validation_outcome(
  p_validation_id text,p_user_id text,p_outcome text,p_rejection_code text DEFAULT NULL,p_http_status integer DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_row public.image_model_validations%ROWTYPE; v_request public.image_generation_requests%ROWTYPE; v_user public.users%ROWTYPE;
BEGIN
  PERFORM public.assert_image_validation_admin(p_user_id);
  SELECT * INTO v_user FROM public.users WHERE id::text=p_user_id FOR UPDATE;
  IF NOT FOUND OR v_user.role IS DISTINCT FROM 'admin' OR v_user.is_active IS DISTINCT FROM true
     OR (v_user.status IS NOT NULL AND v_user.status <> 'active') THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_ADMIN_REQUIRED' USING ERRCODE='42501';
  END IF;
  SELECT * INTO v_row FROM public.image_model_validations WHERE validation_id=p_validation_id FOR UPDATE;
  IF NOT FOUND OR v_row.user_id <> p_user_id THEN RAISE EXCEPTION 'IMAGE_VALIDATION_OWNER_MISMATCH' USING ERRCODE='42501'; END IF;
  IF p_outcome NOT IN ('unknown','rejected','completed') OR p_outcome IS NULL THEN RAISE EXCEPTION 'IMAGE_VALIDATION_OUTCOME_INVALID' USING ERRCODE='22023'; END IF;
  IF v_row.state IN ('rejected','completed','published') THEN
    IF v_row.state <> p_outcome AND NOT (v_row.state='published' AND p_outcome='completed') THEN
      RAISE EXCEPTION 'IMAGE_VALIDATION_TERMINAL_CONFLICT' USING ERRCODE='22023';
    END IF;
    RETURN jsonb_build_object('record',to_jsonb(v_row));
  END IF;
  SELECT * INTO v_request FROM public.image_generation_requests WHERE record_id=v_row.image_record_id FOR UPDATE;
  IF FOUND AND (v_request.user_id<>v_row.user_id OR v_request.client_idempotency_key<>v_row.client_idempotency_key
    OR v_request.client_trace_id<>v_row.client_trace_id OR v_request.payload_fingerprint<>v_row.payload_fingerprint) THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_REQUEST_MISMATCH' USING ERRCODE='22023';
  END IF;
  IF p_outcome='completed' AND (v_request.record_id IS NULL OR v_request.state<>'completed'
     OR coalesce(v_request.response->>'selectedModelId','')<>v_row.model_id) THEN
    RAISE EXCEPTION 'IMAGE_VALIDATION_RESULT_INCOMPLETE' USING ERRCODE='22023';
  END IF;
  IF p_outcome='rejected' THEN
    IF v_request.record_id IS NULL OR v_request.state<>'failed_unknown'
       OR v_request.response->>'schema' IS DISTINCT FROM 'image_request_rejection.v1'
       OR v_request.response->>'payloadFingerprint' IS DISTINCT FROM v_row.payload_fingerprint
       OR v_request.response->>'code' IS DISTINCT FROM p_rejection_code THEN
      RAISE EXCEPTION 'IMAGE_VALIDATION_REJECTION_UNPROVEN' USING ERRCODE='22023';
    END IF;
    IF v_request.response->>'source'='input' THEN
      IF p_rejection_code IS DISTINCT FROM 'IMAGE_REFERENCE_READ_FAILED' OR p_http_status IS NOT NULL
         OR v_request.response->>'upstreamStatus' IS NOT NULL THEN
        RAISE EXCEPTION 'IMAGE_VALIDATION_REJECTION_UNPROVEN' USING ERRCODE='22023';
      END IF;
    ELSIF v_request.response->>'source'='provider' THEN
      IF p_rejection_code='IMAGE_UPSTREAM_TERMINAL_EVENT' THEN
        IF p_http_status IS NOT NULL OR v_request.response->>'upstreamStatus' IS NOT NULL THEN
          RAISE EXCEPTION 'IMAGE_VALIDATION_REJECTION_UNPROVEN' USING ERRCODE='22023';
        END IF;
      ELSIF p_rejection_code='IMAGE_UPSTREAM_ACCOUNT_UNAVAILABLE' THEN
        IF p_http_status IS DISTINCT FROM 503 OR v_request.response->>'upstreamStatus' IS DISTINCT FROM '503' THEN
          RAISE EXCEPTION 'IMAGE_VALIDATION_REJECTION_UNPROVEN' USING ERRCODE='22023';
        END IF;
      ELSIF p_http_status IS NULL OR p_http_status NOT IN (400,401,403,404,422)
         OR v_request.response->>'upstreamStatus' IS DISTINCT FROM p_http_status::text
         OR p_rejection_code IS NULL OR p_rejection_code NOT IN ('IMAGE_REFERENCE_REJECTED','IMAGE_UPSTREAM_REQUEST_REJECTED')
         OR (p_rejection_code='IMAGE_REFERENCE_REJECTED' AND p_http_status<>400) THEN
        RAISE EXCEPTION 'IMAGE_VALIDATION_REJECTION_UNPROVEN' USING ERRCODE='22023';
      END IF;
    ELSE
      RAISE EXCEPTION 'IMAGE_VALIDATION_REJECTION_UNPROVEN' USING ERRCODE='22023';
    END IF;
  END IF;
  IF p_outcome='unknown' AND v_request.state='completed' THEN RAISE EXCEPTION 'IMAGE_VALIDATION_RESULT_ALREADY_COMPLETED' USING ERRCODE='22023'; END IF;
  UPDATE public.image_model_validations SET state=p_outcome,updated_at=now(),
    rejection_code=CASE WHEN p_outcome='rejected' THEN p_rejection_code END,
    rejection_http_status=CASE WHEN p_outcome='rejected' THEN p_http_status END
    WHERE validation_id=p_validation_id RETURNING * INTO v_row;
  RETURN jsonb_build_object('record',to_jsonb(v_row));
END;
$$;

REVOKE ALL ON FUNCTION public.reconcile_image_model_validation_rejection(text,text,timestamptz,timestamptz,text,integer,text,text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reconcile_image_model_validation_rejection(text,text,timestamptz,timestamptz,text,integer,text,text)
  TO service_role;
REVOKE ALL ON FUNCTION public.record_image_model_validation_outcome(text,text,text,text,integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_image_model_validation_outcome(text,text,text,text,integer)
  TO service_role;

COMMIT;
