-- Durable operations-patrol history and alert transitions.
-- Snapshots are append-only; the UI reads the most recent rows. No member data.
create table if not exists public.ops_patrol_snapshots (
  id bigint generated by default as identity primary key,
  captured_at timestamptz not null,
  duration_ms integer not null default 0,
  channels jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists ops_patrol_snapshots_captured_at_idx
  on public.ops_patrol_snapshots (captured_at desc);

alter table public.ops_patrol_snapshots enable row level security;

create table if not exists public.ops_patrol_alerts (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null check (kind in ('degraded', 'down', 'recovered', 'arrears', 'info')),
  channel_host text not null,
  message text not null,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists ops_patrol_alerts_created_at_idx
  on public.ops_patrol_alerts (created_at desc);

alter table public.ops_patrol_alerts enable row level security;

-- Make the new tables visible to PostgREST immediately after apply.
notify pgrst, 'reload schema';

alter table public.ops_patrol_snapshots add column if not exists faults jsonb not null default '[]'::jsonb;
notify pgrst, 'reload schema';
