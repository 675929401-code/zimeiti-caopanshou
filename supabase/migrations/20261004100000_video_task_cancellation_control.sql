-- Durable, owner-scoped video cancellation.
--
-- A browser may ask to stop while its submit response is still pending.  The
-- cancellation intent and video task insert therefore share one advisory lock:
-- either the cancellation tombstone wins and no provider dispatch can start,
-- or the durable task wins and cancellation must follow that task upstream.
BEGIN;
SET LOCAL lock_timeout = '10s';

CREATE TABLE IF NOT EXISTS public.video_task_cancel_intents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL,
  client_request_id text NOT NULL,
  video_task_id text,
  state text NOT NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  last_error_code text,
  CONSTRAINT video_task_cancel_intents_owner_request_unique UNIQUE (user_id, client_request_id),
  CONSTRAINT video_task_cancel_intents_request_check CHECK (
    client_request_id ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,127}$'
  ),
  CONSTRAINT video_task_cancel_intents_state_check CHECK (state IN (
    'cancelled_before_dispatch',
    'upstream_required',
    'upstream_confirmed',
    'terminal_conflict'
  ))
);

CREATE INDEX IF NOT EXISTS video_task_cancel_intents_task_idx
  ON public.video_task_cancel_intents (video_task_id)
  WHERE video_task_id IS NOT NULL;

ALTER TABLE public.video_task_cancel_intents ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.video_task_cancel_intents FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.video_task_cancel_intents TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.video_task_cancel_intents_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.guard_cancelled_video_client_request()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF nullif(trim(coalesce(NEW.user_id::text, '')), '') IS NULL
     OR nullif(trim(coalesce(NEW.client_request_id, '')), '') IS NULL THEN
    RETURN NEW;
  END IF;
  PERFORM pg_advisory_xact_lock(
    hashtext(NEW.user_id::text),
    hashtext(NEW.client_request_id)
  );
  IF EXISTS (
    SELECT 1
      FROM public.video_task_cancel_intents intent
     WHERE intent.user_id = NEW.user_id::text
       AND intent.client_request_id = NEW.client_request_id
       AND intent.state = 'cancelled_before_dispatch'
  ) THEN
    RAISE EXCEPTION 'VIDEO_TASK_CANCELLED_BEFORE_DISPATCH' USING ERRCODE = '57014';
  END IF;
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS guard_cancelled_video_client_request_trigger ON public.video_tasks;
CREATE TRIGGER guard_cancelled_video_client_request_trigger
BEFORE INSERT ON public.video_tasks
FOR EACH ROW EXECUTE FUNCTION public.guard_cancelled_video_client_request();

CREATE OR REPLACE FUNCTION public.request_video_task_cancellation_atomic(
  p_user_id text,
  p_client_request_id text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id text := trim(coalesce(p_user_id, ''));
  v_client_request_id text := trim(coalesce(p_client_request_id, ''));
  v_task public.video_tasks%ROWTYPE;
  v_dispatched boolean := false;
  v_intent_state text;
BEGIN
  IF v_user_id = '' OR v_client_request_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,127}$' THEN
    RAISE EXCEPTION 'VIDEO_CANCELLATION_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext(v_user_id), hashtext(v_client_request_id));
  SELECT * INTO v_task
    FROM public.video_tasks
   WHERE user_id::text = v_user_id
     AND client_request_id = v_client_request_id
   FOR UPDATE;

  IF NOT FOUND THEN
    INSERT INTO public.video_task_cancel_intents (
      user_id, client_request_id, state, requested_at, updated_at, resolved_at
    ) VALUES (
      v_user_id, v_client_request_id, 'cancelled_before_dispatch', now(), now(), now()
    )
    ON CONFLICT (user_id, client_request_id) DO UPDATE
      SET state = CASE
            WHEN video_task_cancel_intents.state IN ('upstream_required', 'upstream_confirmed')
              THEN video_task_cancel_intents.state
            ELSE 'cancelled_before_dispatch'
          END,
          updated_at = now(),
          resolved_at = CASE
            WHEN video_task_cancel_intents.state = 'upstream_confirmed'
              THEN video_task_cancel_intents.resolved_at
            WHEN video_task_cancel_intents.state = 'upstream_required'
              THEN NULL
            ELSE now()
          END,
          last_error_code = NULL
    RETURNING state INTO v_intent_state;
    RETURN jsonb_build_object(
      'status', CASE WHEN v_intent_state = 'upstream_required' THEN 'unknown' ELSE 'cancelled' END,
      'task_found', false,
      'upstream_required', v_intent_state = 'upstream_required',
      'cancellation_state', v_intent_state,
      'reason', CASE
        WHEN v_intent_state = 'upstream_required' THEN 'prior_dispatch_requires_confirmation'
        WHEN v_intent_state = 'upstream_confirmed' THEN 'upstream_confirmed'
        ELSE 'not_dispatched'
      END
    );
  END IF;

  v_dispatched := v_task.provider_dispatch_started_at IS NOT NULL
    OR v_task.provider_dispatch_receipt IS NOT NULL
    OR v_task.provider_submission_receipt IS NOT NULL
    OR nullif(trim(coalesce(v_task.task_id_external, '')), '') IS NOT NULL;

  IF v_task.status IN ('completed', 'failed', 'cancelled', 'expired', 'finalizing') THEN
    INSERT INTO public.video_task_cancel_intents (
      user_id, client_request_id, video_task_id, state, requested_at, updated_at, resolved_at
    ) VALUES (
      v_user_id, v_client_request_id, v_task.id::text,
      CASE
        WHEN v_task.status = 'cancelled' AND NOT v_dispatched THEN 'cancelled_before_dispatch'
        ELSE 'terminal_conflict'
      END,
      now(), now(), now()
    )
    ON CONFLICT (user_id, client_request_id) DO UPDATE
      SET video_task_id = excluded.video_task_id,
          state = excluded.state,
          updated_at = now(),
          resolved_at = now();
    RETURN jsonb_build_object(
      'status', v_task.status,
      'task_found', true,
      'task_id', v_task.id::text,
      'provider_task_id', v_task.task_id_external,
      'model_id', v_task.model_id::text,
      'upstream_required', false,
      'cancellation_state', CASE
        WHEN v_task.status = 'cancelled' AND NOT v_dispatched THEN 'cancelled_before_dispatch'
        ELSE 'terminal_conflict'
      END
    );
  END IF;

  IF NOT v_dispatched THEN
    UPDATE public.video_tasks
       SET status = 'cancelled',
           billing_state = 'submission_failed',
           price_charged = 0,
           submission_error_code = 'USER_CANCELLED_BEFORE_PROVIDER_DISPATCH',
           error_message = '用户已在供应商投递前终止任务，本次未扣费',
           provider_reconciliation_state = 'manual_terminated',
           provider_progress = NULL,
           provider_status_message = '未投递上游，任务已终止',
           provider_last_polled_at = now(),
           completed_at = now()
     WHERE id = v_task.id
       AND status NOT IN ('completed', 'failed', 'cancelled', 'expired');
    INSERT INTO public.video_task_cancel_intents (
      user_id, client_request_id, video_task_id, state, requested_at, updated_at, resolved_at
    ) VALUES (
      v_user_id, v_client_request_id, v_task.id::text,
      'cancelled_before_dispatch', now(), now(), now()
    )
    ON CONFLICT (user_id, client_request_id) DO UPDATE
      SET video_task_id = excluded.video_task_id,
          state = 'cancelled_before_dispatch',
          updated_at = now(),
          resolved_at = now(),
          last_error_code = NULL;
    RETURN jsonb_build_object(
      'status', 'cancelled',
      'task_found', true,
      'task_id', v_task.id::text,
      'model_id', v_task.model_id::text,
      'upstream_required', false,
      'cancellation_state', 'cancelled_before_dispatch',
      'reason', 'not_dispatched'
    );
  END IF;

  INSERT INTO public.video_task_cancel_intents (
    user_id, client_request_id, video_task_id, state, requested_at, updated_at, resolved_at
  ) VALUES (
    v_user_id, v_client_request_id, v_task.id::text,
    'upstream_required', now(), now(), NULL
  )
  ON CONFLICT (user_id, client_request_id) DO UPDATE
    SET video_task_id = excluded.video_task_id,
        state = CASE
          WHEN video_task_cancel_intents.state = 'upstream_confirmed'
            THEN video_task_cancel_intents.state
          ELSE 'upstream_required'
        END,
        updated_at = now(),
        resolved_at = CASE
          WHEN video_task_cancel_intents.state = 'upstream_confirmed'
            THEN video_task_cancel_intents.resolved_at
          ELSE NULL
        END;
  RETURN jsonb_build_object(
    'status', v_task.status,
    'task_found', true,
    'task_id', v_task.id::text,
    'provider_task_id', v_task.task_id_external,
    'model_id', v_task.model_id::text,
    'upstream_required', true,
    'cancellation_state', 'upstream_required'
  );
END
$$;

CREATE OR REPLACE FUNCTION public.confirm_video_task_upstream_cancellation_atomic(
  p_user_id text,
  p_client_request_id text,
  p_task_id text,
  p_provider_task_id text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id text := trim(coalesce(p_user_id, ''));
  v_client_request_id text := trim(coalesce(p_client_request_id, ''));
  v_task public.video_tasks%ROWTYPE;
BEGIN
  IF v_user_id = ''
     OR v_client_request_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,127}$'
     OR nullif(trim(coalesce(p_task_id, '')), '') IS NULL
     OR nullif(trim(coalesce(p_provider_task_id, '')), '') IS NULL THEN
    RAISE EXCEPTION 'VIDEO_CANCELLATION_CONFIRMATION_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext(v_user_id), hashtext(v_client_request_id));
  SELECT * INTO v_task
    FROM public.video_tasks
   WHERE id::text = trim(p_task_id)
     AND user_id::text = v_user_id
     AND client_request_id = v_client_request_id
   FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'VIDEO_CANCELLATION_TASK_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF nullif(trim(coalesce(v_task.task_id_external, '')), '') IS NULL
     OR v_task.task_id_external IS DISTINCT FROM trim(p_provider_task_id) THEN
    RAISE EXCEPTION 'VIDEO_CANCELLATION_PROVIDER_TASK_MISMATCH' USING ERRCODE = '23514';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.video_task_cancel_intents intent
     WHERE intent.user_id = v_user_id
       AND intent.client_request_id = v_client_request_id
       AND intent.video_task_id = v_task.id::text
       AND intent.state IN ('upstream_required', 'upstream_confirmed')
  ) THEN
    RAISE EXCEPTION 'VIDEO_CANCELLATION_INTENT_REQUIRED' USING ERRCODE = '23514';
  END IF;

  IF v_task.status = 'cancelled' THEN
    RETURN jsonb_build_object('status', 'cancelled', 'already_cancelled', true);
  END IF;
  IF v_task.status IN ('completed', 'failed', 'expired', 'finalizing')
     OR v_task.billing_operation_id IS NOT NULL
     OR coalesce(v_task.price_charged, 0) <> 0 THEN
    RETURN jsonb_build_object('status', v_task.status, 'terminal_conflict', true);
  END IF;

  UPDATE public.video_tasks
     SET status = 'cancelled',
         billing_state = 'failed',
         price_charged = 0,
         submission_error_code = 'USER_CANCELLED_UPSTREAM_CONFIRMED',
         error_message = '上游已确认用户终止任务',
         provider_reconciliation_state = 'manual_terminated',
         provider_progress = NULL,
         provider_status_message = '上游已确认终止',
         provider_last_polled_at = now(),
         completed_at = now()
   WHERE id = v_task.id
     AND status NOT IN ('completed', 'failed', 'cancelled', 'expired', 'finalizing');

  UPDATE public.video_task_cancel_intents
     SET state = 'upstream_confirmed', updated_at = now(), resolved_at = now(), last_error_code = NULL
   WHERE user_id = v_user_id
     AND client_request_id = v_client_request_id
     AND video_task_id = v_task.id::text;
  RETURN jsonb_build_object('status', 'cancelled', 'already_cancelled', false);
END
$$;

REVOKE ALL ON FUNCTION public.guard_cancelled_video_client_request() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.request_video_task_cancellation_atomic(text,text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.confirm_video_task_upstream_cancellation_atomic(text,text,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.request_video_task_cancellation_atomic(text,text) TO service_role;
GRANT EXECUTE ON FUNCTION public.confirm_video_task_upstream_cancellation_atomic(text,text,text,text) TO service_role;

COMMENT ON TABLE public.video_task_cancel_intents IS
  'Owner-scoped cancellation tombstones that fence video submission and record whether upstream confirmation is required.';
COMMENT ON FUNCTION public.request_video_task_cancellation_atomic(text,text) IS
  'Linearizes cancellation against task reservation. It may terminate only work with no provider dispatch evidence; dispatched tasks require exact upstream confirmation.';

NOTIFY pgrst, 'reload schema';
COMMIT;
