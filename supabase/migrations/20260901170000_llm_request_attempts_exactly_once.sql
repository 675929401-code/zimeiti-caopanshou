-- Durable, multi-instance exactly-once state machine for /api/llm.
-- External LLM calls cannot join the database transaction. The lease/fencing
-- token coordinates workers before dispatch; once provider_call_started_at is
-- set, an expired running attempt is frozen for reconciliation and can never
-- be silently submitted again.

CREATE TABLE IF NOT EXISTS public.llm_request_attempts (
  record_id text PRIMARY KEY,
  user_id text NOT NULL,
  client_request_id text NOT NULL,
  payload_fingerprint text NOT NULL,
  state text NOT NULL DEFAULT 'running'
    CHECK (state IN ('running', 'succeeded', 'failed', 'failed_unknown', 'reconciliation_required')),
  attempt_no integer NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
  lease_owner text,
  lease_token bigint NOT NULL DEFAULT 1 CHECK (lease_token > 0),
  lease_expires_at timestamptz,
  provider_call_started_at timestamptz,
  http_status integer,
  response_headers jsonb NOT NULL DEFAULT '{}'::jsonb,
  response_body text,
  response_fingerprint text,
  result_reference text,
  error_code text,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT llm_request_attempts_user_request_unique UNIQUE (user_id, client_request_id),
  CONSTRAINT llm_request_attempts_record_id_format CHECK (record_id ~ '^[a-f0-9]{64}$'),
  CONSTRAINT llm_request_attempts_client_request_format CHECK (
    client_request_id ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,127}$'
  ),
  CONSTRAINT llm_request_attempts_payload_hash_format CHECK (payload_fingerprint ~ '^[a-f0-9]{64}$'),
  CONSTRAINT llm_request_attempts_response_hash_format CHECK (
    response_fingerprint IS NULL OR response_fingerprint ~ '^[a-f0-9]{64}$'
  ),
  CONSTRAINT llm_request_attempts_response_headers_object CHECK (jsonb_typeof(response_headers) = 'object'),
  CONSTRAINT llm_request_attempts_http_status_range CHECK (
    http_status IS NULL OR http_status BETWEEN 100 AND 599
  ),
  CONSTRAINT llm_request_attempts_response_size CHECK (
    response_body IS NULL OR octet_length(response_body) <= 8388608
  ),
  CONSTRAINT llm_request_attempts_terminal_shape CHECK (
    (state = 'running' AND response_body IS NULL AND response_fingerprint IS NULL AND result_reference IS NULL)
    OR (state = 'succeeded' AND http_status BETWEEN 200 AND 299 AND response_body IS NOT NULL
        AND response_fingerprint IS NOT NULL AND result_reference IS NOT NULL)
    OR (state = 'failed' AND http_status IS NOT NULL AND response_body IS NOT NULL
        AND response_fingerprint IS NOT NULL AND result_reference IS NULL)
    OR (state IN ('failed_unknown', 'reconciliation_required') AND response_body IS NULL
        AND response_fingerprint IS NULL AND result_reference IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS llm_request_attempts_user_updated_idx
  ON public.llm_request_attempts (user_id, updated_at DESC);

CREATE INDEX IF NOT EXISTS llm_request_attempts_reconciliation_idx
  ON public.llm_request_attempts (state, updated_at ASC)
  WHERE state IN ('running', 'failed_unknown', 'reconciliation_required');

ALTER TABLE public.llm_request_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.llm_request_attempts FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.llm_request_attempts TO service_role;

CREATE TABLE IF NOT EXISTS public.llm_request_attempt_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id text NOT NULL REFERENCES public.llm_request_attempts(record_id),
  attempt_no integer NOT NULL CHECK (attempt_no > 0),
  event_type text NOT NULL CHECK (
    event_type IN ('claimed', 'lease_reclaimed', 'retry_claimed', 'provider_started',
                   'succeeded', 'failed', 'failed_unknown', 'reconciliation_required', 'reconciled')
  ),
  from_state text,
  to_state text NOT NULL
    CHECK (to_state IN ('running', 'succeeded', 'failed', 'failed_unknown', 'reconciliation_required')),
  lease_owner text,
  lease_token bigint NOT NULL CHECK (lease_token > 0),
  actor_user_id text,
  reason text,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT llm_request_attempt_events_evidence_object CHECK (jsonb_typeof(evidence) = 'object')
);

CREATE INDEX IF NOT EXISTS llm_request_attempt_events_record_idx
  ON public.llm_request_attempt_events (record_id, id ASC);

ALTER TABLE public.llm_request_attempt_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.llm_request_attempt_events FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.llm_request_attempt_events TO service_role;

CREATE OR REPLACE FUNCTION public.claim_llm_request_attempt_atomic(
  p_record_id text,
  p_user_id text,
  p_client_request_id text,
  p_payload_fingerprint text,
  p_lease_owner text,
  p_lease_seconds integer DEFAULT 900
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_row public.llm_request_attempts%ROWTYPE;
  v_action text;
  v_created boolean := false;
  v_user_id text := trim(coalesce(p_user_id, ''));
  v_client_request_id text := trim(coalesce(p_client_request_id, ''));
  v_fingerprint text := lower(trim(coalesce(p_payload_fingerprint, '')));
  v_lease_owner text := trim(coalesce(p_lease_owner, ''));
  v_lease_seconds integer := greatest(30, least(coalesce(p_lease_seconds, 900), 900));
BEGIN
  IF trim(coalesce(p_record_id, '')) !~ '^[a-f0-9]{64}$'
     OR v_user_id = ''
     OR v_client_request_id !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,127}$'
     OR v_fingerprint !~ '^[a-f0-9]{64}$'
     OR v_lease_owner = '' THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(v_user_id || ':' || v_client_request_id, 0));

  INSERT INTO public.llm_request_attempts (
    record_id, user_id, client_request_id, payload_fingerprint,
    state, attempt_no, lease_owner, lease_token, lease_expires_at
  ) VALUES (
    trim(p_record_id), v_user_id, v_client_request_id, v_fingerprint,
    'running', 1, v_lease_owner, 1, now() + make_interval(secs => v_lease_seconds)
  )
  ON CONFLICT (user_id, client_request_id) DO NOTHING
  RETURNING * INTO v_row;

  v_created := FOUND;
  IF v_created THEN
    v_action := 'execute';
    INSERT INTO public.llm_request_attempt_events (
      record_id, attempt_no, event_type, to_state, lease_owner, lease_token
    ) VALUES (v_row.record_id, v_row.attempt_no, 'claimed', 'running', v_row.lease_owner, v_row.lease_token);
  ELSE
    SELECT * INTO v_row
      FROM public.llm_request_attempts
     WHERE user_id = v_user_id AND client_request_id = v_client_request_id
     FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'LLM_ATTEMPT_LOOKUP_FAILED'; END IF;
    IF v_row.record_id <> trim(p_record_id) OR v_row.payload_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'LLM_ATTEMPT_PAYLOAD_CONFLICT' USING ERRCODE = '22023';
    END IF;

    CASE v_row.state
      WHEN 'succeeded' THEN
        v_action := 'replay';
      WHEN 'failed_unknown' THEN
        v_action := 'reconciliation_required';
      WHEN 'reconciliation_required' THEN
        v_action := 'reconciliation_required';
      WHEN 'failed' THEN
        INSERT INTO public.llm_request_attempt_events (
          record_id, attempt_no, event_type, from_state, to_state,
          lease_owner, lease_token, reason, evidence
        ) VALUES (
          v_row.record_id, v_row.attempt_no + 1, 'retry_claimed', 'failed', 'running',
          v_lease_owner, v_row.lease_token + 1, 'definitive_failure_retry',
          jsonb_build_object(
            'prior_error_code', v_row.error_code,
            'prior_http_status', v_row.http_status,
            'prior_response_fingerprint', v_row.response_fingerprint
          )
        );
        UPDATE public.llm_request_attempts
           SET state = 'running', attempt_no = attempt_no + 1,
               lease_owner = v_lease_owner, lease_token = lease_token + 1,
               lease_expires_at = now() + make_interval(secs => v_lease_seconds),
               provider_call_started_at = NULL, http_status = NULL,
               response_headers = '{}'::jsonb, response_body = NULL,
               response_fingerprint = NULL, result_reference = NULL,
               error_code = NULL, error_message = NULL, updated_at = now()
         WHERE record_id = v_row.record_id
         RETURNING * INTO v_row;
        v_action := 'execute';
      WHEN 'running' THEN
        IF v_row.lease_expires_at IS NOT NULL AND v_row.lease_expires_at > now() THEN
          v_action := 'in_progress';
        ELSIF v_row.provider_call_started_at IS NOT NULL THEN
          UPDATE public.llm_request_attempts
             SET state = 'reconciliation_required', lease_owner = NULL,
                 lease_expires_at = NULL, error_code = 'LLM_STALE_AFTER_PROVIDER_START',
                 error_message = 'lease expired after provider dispatch', updated_at = now()
           WHERE record_id = v_row.record_id
           RETURNING * INTO v_row;
          INSERT INTO public.llm_request_attempt_events (
            record_id, attempt_no, event_type, from_state, to_state,
            lease_token, reason, evidence
          ) VALUES (
            v_row.record_id, v_row.attempt_no, 'reconciliation_required', 'running',
            'reconciliation_required', v_row.lease_token, 'stale_after_provider_start',
            jsonb_build_object('provider_call_started_at', v_row.provider_call_started_at)
          );
          v_action := 'reconciliation_required';
        ELSE
          UPDATE public.llm_request_attempts
             SET lease_owner = v_lease_owner, lease_token = lease_token + 1,
                 lease_expires_at = now() + make_interval(secs => v_lease_seconds),
                 updated_at = now()
           WHERE record_id = v_row.record_id
           RETURNING * INTO v_row;
          INSERT INTO public.llm_request_attempt_events (
            record_id, attempt_no, event_type, from_state, to_state,
            lease_owner, lease_token, reason
          ) VALUES (
            v_row.record_id, v_row.attempt_no, 'lease_reclaimed', 'running', 'running',
            v_row.lease_owner, v_row.lease_token, 'expired_before_provider_start'
          );
          v_action := 'execute';
        END IF;
      ELSE
        RAISE EXCEPTION 'LLM_ATTEMPT_STATE_INVALID' USING ERRCODE = '22023';
    END CASE;
  END IF;

  RETURN jsonb_build_object('action', v_action, 'record', to_jsonb(v_row));
END;
$$;

CREATE OR REPLACE FUNCTION public.mark_llm_request_provider_started_atomic(
  p_record_id text,
  p_payload_fingerprint text,
  p_lease_owner text,
  p_lease_token bigint
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_row public.llm_request_attempts%ROWTYPE;
BEGIN
  SELECT * INTO v_row FROM public.llm_request_attempts
   WHERE record_id = trim(coalesce(p_record_id, '')) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'LLM_ATTEMPT_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF v_row.payload_fingerprint <> lower(trim(coalesce(p_payload_fingerprint, '')))
     OR v_row.state <> 'running'
     OR v_row.lease_owner <> trim(coalesce(p_lease_owner, ''))
     OR v_row.lease_token <> p_lease_token THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_LEASE_CONFLICT' USING ERRCODE = '22023';
  END IF;

  IF v_row.provider_call_started_at IS NULL THEN
    UPDATE public.llm_request_attempts
       SET provider_call_started_at = now(), updated_at = now()
     WHERE record_id = v_row.record_id RETURNING * INTO v_row;
    INSERT INTO public.llm_request_attempt_events (
      record_id, attempt_no, event_type, from_state, to_state,
      lease_owner, lease_token, evidence
    ) VALUES (
      v_row.record_id, v_row.attempt_no, 'provider_started', 'running', 'running',
      v_row.lease_owner, v_row.lease_token,
      jsonb_build_object('provider_call_started_at', v_row.provider_call_started_at)
    );
  END IF;
  RETURN jsonb_build_object('record', to_jsonb(v_row));
END;
$$;

CREATE OR REPLACE FUNCTION public.finalize_llm_request_attempt_atomic(
  p_record_id text,
  p_payload_fingerprint text,
  p_lease_owner text,
  p_lease_token bigint,
  p_state text,
  p_http_status integer DEFAULT NULL,
  p_response_headers jsonb DEFAULT '{}'::jsonb,
  p_response_body text DEFAULT NULL,
  p_response_fingerprint text DEFAULT NULL,
  p_result_reference text DEFAULT NULL,
  p_error_code text DEFAULT NULL,
  p_error_message text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_row public.llm_request_attempts%ROWTYPE;
  v_state text := lower(trim(coalesce(p_state, '')));
  v_fingerprint text := lower(trim(coalesce(p_payload_fingerprint, '')));
BEGIN
  IF v_state NOT IN ('succeeded', 'failed', 'failed_unknown', 'reconciliation_required')
     OR jsonb_typeof(coalesce(p_response_headers, '{}'::jsonb)) <> 'object' THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_FINALIZE_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  IF v_state = 'succeeded' AND (
    p_http_status NOT BETWEEN 200 AND 299 OR p_response_body IS NULL
    OR trim(coalesce(p_response_fingerprint, '')) !~ '^[a-f0-9]{64}$'
    OR trim(coalesce(p_result_reference, '')) = ''
  ) THEN RAISE EXCEPTION 'LLM_ATTEMPT_SUCCESS_EVIDENCE_REQUIRED' USING ERRCODE = '22023'; END IF;
  IF v_state = 'failed' AND (
    p_http_status IS NULL OR p_response_body IS NULL
    OR trim(coalesce(p_response_fingerprint, '')) !~ '^[a-f0-9]{64}$'
  ) THEN RAISE EXCEPTION 'LLM_ATTEMPT_FAILURE_EVIDENCE_REQUIRED' USING ERRCODE = '22023'; END IF;
  IF v_state IN ('failed_unknown', 'reconciliation_required') AND p_response_body IS NOT NULL THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_UNKNOWN_RESPONSE_FORBIDDEN' USING ERRCODE = '22023';
  END IF;
  IF p_response_body IS NOT NULL AND octet_length(p_response_body) > 8388608 THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_RESPONSE_TOO_LARGE' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_row FROM public.llm_request_attempts
   WHERE record_id = trim(coalesce(p_record_id, '')) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'LLM_ATTEMPT_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF v_row.payload_fingerprint <> v_fingerprint THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_PAYLOAD_CONFLICT' USING ERRCODE = '22023';
  END IF;

  IF v_row.state <> 'running' THEN
    IF v_row.state <> v_state THEN
      RAISE EXCEPTION 'LLM_ATTEMPT_TERMINAL_CONFLICT' USING ERRCODE = '22023';
    END IF;
    IF v_state = 'succeeded' AND (
      v_row.http_status IS DISTINCT FROM p_http_status
      OR v_row.response_fingerprint IS DISTINCT FROM trim(p_response_fingerprint)
      OR v_row.result_reference IS DISTINCT FROM trim(p_result_reference)
    ) THEN RAISE EXCEPTION 'LLM_ATTEMPT_RESULT_CONFLICT' USING ERRCODE = '22023'; END IF;
    IF v_state = 'failed' AND (
      v_row.http_status IS DISTINCT FROM p_http_status
      OR v_row.response_fingerprint IS DISTINCT FROM trim(p_response_fingerprint)
    ) THEN RAISE EXCEPTION 'LLM_ATTEMPT_RESULT_CONFLICT' USING ERRCODE = '22023'; END IF;
    RETURN jsonb_build_object('record', to_jsonb(v_row));
  END IF;

  IF v_row.lease_owner <> trim(coalesce(p_lease_owner, '')) OR v_row.lease_token <> p_lease_token THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_LEASE_CONFLICT' USING ERRCODE = '22023';
  END IF;
  IF v_state = 'succeeded' AND v_row.provider_call_started_at IS NULL THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_PROVIDER_START_REQUIRED' USING ERRCODE = '22023';
  END IF;

  UPDATE public.llm_request_attempts
     SET state = v_state, lease_owner = NULL, lease_expires_at = NULL,
         http_status = CASE WHEN v_state IN ('succeeded', 'failed') THEN p_http_status ELSE NULL END,
         response_headers = CASE WHEN v_state IN ('succeeded', 'failed') THEN coalesce(p_response_headers, '{}'::jsonb) ELSE '{}'::jsonb END,
         response_body = CASE WHEN v_state IN ('succeeded', 'failed') THEN p_response_body ELSE NULL END,
         response_fingerprint = CASE WHEN v_state IN ('succeeded', 'failed') THEN lower(trim(p_response_fingerprint)) ELSE NULL END,
         result_reference = CASE WHEN v_state = 'succeeded' THEN trim(p_result_reference) ELSE NULL END,
         error_code = nullif(left(trim(coalesce(p_error_code, '')), 120), ''),
         error_message = nullif(left(trim(coalesce(p_error_message, '')), 500), ''),
         updated_at = now()
   WHERE record_id = v_row.record_id RETURNING * INTO v_row;

  INSERT INTO public.llm_request_attempt_events (
    record_id, attempt_no, event_type, from_state, to_state,
    lease_token, reason, evidence
  ) VALUES (
    v_row.record_id, v_row.attempt_no, v_state, 'running', v_state,
    v_row.lease_token, nullif(left(trim(coalesce(p_error_message, '')), 500), ''),
    jsonb_strip_nulls(jsonb_build_object(
      'http_status', v_row.http_status,
      'response_fingerprint', v_row.response_fingerprint,
      'result_reference', v_row.result_reference,
      'error_code', v_row.error_code
    ))
  );
  RETURN jsonb_build_object('record', to_jsonb(v_row));
END;
$$;

CREATE OR REPLACE FUNCTION public.reconcile_llm_request_attempt_atomic(
  p_record_id text,
  p_expected_attempt_no integer,
  p_actor_user_id text,
  p_target_state text,
  p_reason text,
  p_http_status integer DEFAULT NULL,
  p_response_headers jsonb DEFAULT '{}'::jsonb,
  p_response_body text DEFAULT NULL,
  p_response_fingerprint text DEFAULT NULL,
  p_result_reference text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_row public.llm_request_attempts%ROWTYPE;
  v_target text := lower(trim(coalesce(p_target_state, '')));
  v_reason text := trim(coalesce(p_reason, ''));
  v_from_state text;
BEGIN
  IF v_target NOT IN ('succeeded', 'failed')
     OR trim(coalesce(p_actor_user_id, '')) = ''
     OR char_length(v_reason) NOT BETWEEN 8 AND 500 THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_RECONCILIATION_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  IF v_target = 'succeeded' AND (
    p_http_status NOT BETWEEN 200 AND 299 OR p_response_body IS NULL
    OR trim(coalesce(p_response_fingerprint, '')) !~ '^[a-f0-9]{64}$'
    OR trim(coalesce(p_result_reference, '')) = ''
  ) THEN RAISE EXCEPTION 'LLM_ATTEMPT_SUCCESS_EVIDENCE_REQUIRED' USING ERRCODE = '22023'; END IF;
  IF v_target = 'failed' AND (
    p_http_status IS NULL OR p_response_body IS NULL
    OR trim(coalesce(p_response_fingerprint, '')) !~ '^[a-f0-9]{64}$'
  ) THEN RAISE EXCEPTION 'LLM_ATTEMPT_FAILURE_EVIDENCE_REQUIRED' USING ERRCODE = '22023'; END IF;
  IF p_response_body IS NOT NULL AND octet_length(p_response_body) > 8388608 THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_RESPONSE_TOO_LARGE' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_row FROM public.llm_request_attempts
   WHERE record_id = trim(coalesce(p_record_id, '')) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'LLM_ATTEMPT_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF v_row.attempt_no <> p_expected_attempt_no
     OR v_row.state NOT IN ('running', 'failed_unknown', 'reconciliation_required') THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_RECONCILIATION_CONFLICT' USING ERRCODE = '22023';
  END IF;
  IF v_row.state = 'running' AND (
    v_row.provider_call_started_at IS NULL
    OR (v_row.lease_expires_at IS NOT NULL AND v_row.lease_expires_at > now())
  ) THEN
    RAISE EXCEPTION 'LLM_ATTEMPT_RECONCILIATION_NOT_READY' USING ERRCODE = '22023';
  END IF;
  v_from_state := v_row.state;

  UPDATE public.llm_request_attempts
     SET state = v_target, lease_owner = NULL, lease_expires_at = NULL,
         http_status = p_http_status, response_headers = coalesce(p_response_headers, '{}'::jsonb),
         response_body = p_response_body, response_fingerprint = lower(trim(p_response_fingerprint)),
         result_reference = CASE WHEN v_target = 'succeeded' THEN trim(p_result_reference) ELSE NULL END,
         error_code = CASE WHEN v_target = 'failed' THEN 'LLM_RECONCILED_FAILURE' ELSE NULL END,
         error_message = v_reason, updated_at = now()
   WHERE record_id = v_row.record_id RETURNING * INTO v_row;

  INSERT INTO public.llm_request_attempt_events (
    record_id, attempt_no, event_type, from_state, to_state,
    lease_token, actor_user_id, reason, evidence
  ) VALUES (
    v_row.record_id, v_row.attempt_no, 'reconciled', v_from_state, v_target,
    v_row.lease_token, trim(p_actor_user_id), v_reason,
    jsonb_build_object('http_status', p_http_status, 'response_fingerprint', p_response_fingerprint)
  );
  RETURN jsonb_build_object('record', to_jsonb(v_row));
END;
$$;

